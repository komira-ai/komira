-- The table of the decimal compare tests whose comparison DuckDB cannot make: `tx`,
-- built by the pinned DuckDB. Four nullable DECIMAL columns, each holding
-- values of both signs at a size where widening the column to a longer scale
-- (what DuckDB does to compare it with a literal of more scale) overflows
-- DECIMAL(38) from a known scale on:
--   xq  DECIMAL(38, 2)   +-10^20, which is 10^22 hundredths: scale 18 on
--   xr  DECIMAL(38, 0)   +-(10^38 - 1): any scale on
--   xs  DECIMAL(15, 2)   +-9999999999999.99: scale 26 on
--   xw  DECIMAL(38, 10)  +-10^27, which is 10^37 ten-billionths: scale 11 on

CREATE TABLE tx AS
SELECT * FROM (VALUES
  (1::BIGINT, 0.00::DECIMAL(38, 2), 0::DECIMAL(38, 0), 0.00::DECIMAL(15, 2), 0.0000000000::DECIMAL(38, 10)),
  (2::BIGINT, 0.01::DECIMAL(38, 2), 1::DECIMAL(38, 0), 0.01::DECIMAL(15, 2), 0.0000000001::DECIMAL(38, 10)),
  (3::BIGINT, -0.01::DECIMAL(38, 2), -1::DECIMAL(38, 0), -0.01::DECIMAL(15, 2), -0.0000000001::DECIMAL(38, 10)),
  (4::BIGINT, 0.06::DECIMAL(38, 2), 2::DECIMAL(38, 0), 0.06::DECIMAL(15, 2), 0.0000000003::DECIMAL(38, 10)),
  (5::BIGINT, 100000000000000000000.00::DECIMAL(38, 2), 99999999999999999999999999999999999999::DECIMAL(38, 0), 9999999999999.99::DECIMAL(15, 2), 1000000000000000000000000000.0000000000::DECIMAL(38, 10)),
  (6::BIGINT, -100000000000000000000.00::DECIMAL(38, 2), -99999999999999999999999999999999999999::DECIMAL(38, 0), -9999999999999.99::DECIMAL(15, 2), -1000000000000000000000000000.0000000000::DECIMAL(38, 10)),
  (7::BIGINT, 99999999999999999999.99::DECIMAL(38, 2), 99999999999999999999999999999999999998::DECIMAL(38, 0), 9999999999999.98::DECIMAL(15, 2), 999999999999999999999999999.9999999999::DECIMAL(38, 10)),
  (8::BIGINT, 0.07::DECIMAL(38, 2), 5::DECIMAL(38, 0), 0.07::DECIMAL(15, 2), 0.0000000005::DECIMAL(38, 10)),
  (9::BIGINT, NULL::DECIMAL(38, 2), NULL::DECIMAL(38, 0), NULL::DECIMAL(15, 2), NULL::DECIMAL(38, 10))
) AS e(id, xq, xr, xs, xw);
