//! The OpenAPI emitter: the IR rendered as one OpenAPI v3 YAML document.

use std::fmt::Write as _;

use crate::ir::*;
use crate::path_template::{partition_fields, BodyDesignator, PathTemplate};

/// Emit the whole `IrModel` as a single OpenAPI v3 YAML document.
///
/// One document per plugin invocation — OpenAPI is a whole-API artifact,
/// not a per-file one (unlike the Mojo emitter, which is one `.mojo` per
/// `.proto`). The component schemas are keyed by the resolved flat Mojo
/// name so two files with same-named proto messages do not collide.
pub fn emit_openapi(model: &IrModel) -> String {
    let mut w = YamlWriter::new();

    // -- openapi version + info ----------------------------------------
    w.line("# GENERATED by protoc-gen-openapi — do not hand-edit.");
    w.line("# The OpenAPI v3 REST projection of the proto service corpus");
    w.line("# (proto_codegen_v04.md §8.1). Source of truth: the .proto files.");
    w.line("openapi: 3.0.3");
    w.line("info:");
    w.indent();
    w.line("title: Komira API");
    w.line(&format!(
        "description: OpenAPI v3 projection of {} proto file(s).",
        model.files.len()
    ));
    w.line("version: 0.4.0");
    w.dedent();

    let grouped = group_operations_by_path(model);
    let mut paths_buf = YamlWriter::new();
    paths_buf.indent();
    for (path_key, ops) in &grouped {
        emit_path_item(&mut paths_buf, model, path_key, ops);
    }
    if !grouped.is_empty() {
        w.line("paths:");
        w.append(&paths_buf);
    } else {
        // A pure-message corpus (no services) — OpenAPI requires the
        // `paths` field; an empty object is the spec-correct value.
        w.line("paths: {}");
    }

    // -- components/schemas --------------------------------------------
    w.line("components:");
    w.indent();
    w.line("schemas:");
    w.indent();
    let mut emitted: Vec<String> = Vec::new();
    for file in &model.files {
        for en in &file.enums {
            emit_enum_schema(&mut w, en);
            emitted.push(en.mojo_name.clone());
        }
        for msg in &file.messages {
            if msg.is_map_entry {
                continue;
            }
            emit_message_schema(&mut w, msg);
            emitted.push(msg.mojo_name.clone());
        }
    }
    for name in referenced_but_absent(model, &emitted) {
        emit_stub_schema(&mut w, &name);
    }
    w.dedent();
    w.dedent();

    w.finish()
}

/// One OpenAPI Operation to emit — a `(verb, service, method)` triple, plus the
/// resolved http rule (`None` = the un-annotated Connect fallback). Several
/// operations may share one `path_key` (different verbs), so the grouping keys
/// on the path and holds these as the ordered verb children. A rule's
/// `additional_bindings` are operations of their own, each at its own path:
/// `binding` is 0 for the rule itself and `i` for its `i`th additional
/// binding, which suffixes the `operationId` so that it stays unique.
struct Operation<'a> {
    verb: String,
    svc: &'a IrService,
    method: &'a IrMethod,
    rule: Option<&'a IrHttpRule>,
    binding: usize,
}

fn group_operations_by_path(model: &IrModel) -> Vec<(String, Vec<Operation<'_>>)> {
    let mut groups: Vec<(String, Vec<Operation<'_>>)> = Vec::new();
    for file in &model.files {
        for svc in &file.services {
            for method in &svc.methods {
                let ops: Vec<(String, Operation<'_>)> = match &method.http_rule {
                    Some(r) => std::iter::once(r)
                        .chain(r.additional_bindings.iter())
                        .enumerate()
                        .map(|(binding, b)| {
                            let verb = b.verb.clone();
                            let op = Operation { verb, svc, method, rule: Some(b), binding };
                            (b.path_template.clone(), op)
                        })
                        .collect(),
                    None => vec![(
                        format!("/{}/{}", svc.name, method.name),
                        Operation {
                            verb: "post".to_string(),
                            svc,
                            method,
                            rule: None,
                            binding: 0,
                        },
                    )],
                };
                for (path_key, op) in ops {
                    match groups.iter_mut().find(|(k, _)| *k == path_key) {
                        Some((_, ops)) => ops.push(op),
                        None => groups.push((path_key, vec![op])),
                    }
                }
            }
        }
    }
    groups
}

fn emit_path_item(
    w: &mut YamlWriter,
    model: &IrModel,
    path_key: &str,
    ops: &[Operation<'_>],
) {
    w.line(&format!("{path_key}:"));
    w.indent();
    for op in ops {
        emit_operation(w, model, op);
    }
    w.dedent();
}

/// One verb Operation under an already-emitted path key. Net-zero on the
/// writer's depth (enters at the operation-verb level, returns to it).
fn emit_operation(w: &mut YamlWriter, model: &IrModel, op: &Operation<'_>) {
    let method = op.method;
    let svc = op.svc;

    // The request's leaf-field partition (path / body / query). Only an
    // annotated method with a well-formed template partitions; an un-annotated
    // method (or a template that does not partition) uses the whole-body
    // Connect projection.
    let input_msg = model.files.iter().flat_map(|f| f.messages.iter()).find(|m| {
        m.mojo_name == method.input.mojo_name || m.fq_name == method.input.fq_name
    });
    let partition = op.rule.and_then(|rule| {
        input_msg.and_then(|msg| {
            let leaf_names: Vec<String> = msg.fields.iter().map(|f| f.name.clone()).collect();
            // A `{field=pattern}` variable has no OpenAPI spelling (the path
            // key is the template text, so its parameter name would not
            // match): such a template keeps the whole-body projection, and so
            // does a dotted `{a.b}` variable, which names no request field.
            PathTemplate::parse(&rule.path_template)
                .ok()
                .filter(|t| !t.has_patterns() && !t.has_nested_vars())
                .and_then(|t| partition_fields(&leaf_names, &t, &rule.body).ok())
        })
    });

    w.line(&format!("{}:", op.verb));
    w.indent();
    if op.binding == 0 {
        w.line(&format!("operationId: {}_{}", svc.name, method.name));
    } else {
        w.line(&format!("operationId: {}_{}_{}", svc.name, method.name, op.binding + 1));
    }
    w.line(&format!(
        "summary: {} RPC ({}).",
        method.name,
        streaming_token(method)
    ));

    match &partition {
        // The annotated REST projection — path/query params + partitioned body.
        Some(partition) => {
            let has_params =
                !partition.path_fields.is_empty() || !partition.query_fields.is_empty();
            if has_params {
                w.line("parameters:");
                for pf in &partition.path_fields {
                    emit_parameter(w, input_msg, pf, "path", true);
                }
                for qf in &partition.query_fields {
                    emit_parameter(w, input_msg, qf, "query", false);
                }
            }
            match &partition.body {
                BodyDesignator::Whole => {
                    emit_request_body_whole(w, &method.input.mojo_name)
                }
                BodyDesignator::Field(field_name) => {
                    emit_request_body_field(w, input_msg, field_name);
                }
                BodyDesignator::None => {}
            }
        }
        // The un-annotated fallback (or a non-partitioning template) — the whole
        // request is the body, no path/query params.
        None => emit_request_body_whole(w, &method.input.mojo_name),
    }

    emit_ok_response(w, method);
    w.dedent();
}

/// The `requestBody` block for a whole-message body (`body: "*"` or the
/// un-annotated fallback) — a `$ref` to the input message schema.
fn emit_request_body_whole(w: &mut YamlWriter, input_mojo_name: &str) {
    w.line("requestBody:");
    w.indent();
    w.line("required: true");
    w.line("content:");
    w.indent();
    w.line("application/json:");
    w.indent();
    w.line("schema:");
    w.indent();
    w.line(&format!("$ref: '#/components/schemas/{input_mojo_name}'"));
    w.dedent();
    w.dedent();
    w.dedent();
    w.dedent();
}

/// The `requestBody` block for a single named body field (`body: "<field>"`) —
/// the field's own schema is inlined as the body.
fn emit_request_body_field(w: &mut YamlWriter, input_msg: Option<&IrMessage>, field_name: &str) {
    w.line("requestBody:");
    w.indent();
    w.line("required: true");
    w.line("content:");
    w.indent();
    w.line("application/json:");
    w.indent();
    w.line("schema:");
    w.indent();
    match input_msg.and_then(|m| m.fields.iter().find(|f| f.name == field_name)) {
        Some(field) => write_field_type_schema(w, field),
        // The partition already validated the field exists; a defensive
        // fallback keeps the document well-formed.
        None => w.line("type: object"),
    }
    w.dedent();
    w.dedent();
    w.dedent();
    w.dedent();
}

/// One path/query `parameters` entry, resolved against the input message so it
/// carries the field's proto3-JSON schema.
fn emit_parameter(
    w: &mut YamlWriter,
    input_msg: Option<&IrMessage>,
    field_name: &str,
    location: &str,
    required: bool,
) {
    let field = input_msg.and_then(|m| m.fields.iter().find(|f| f.name == field_name));
    // The parameter name is the proto3-JSON key (the wire key the URL carries).
    let param_name = field.map(|f| f.json_name.as_str()).unwrap_or(field_name);
    w.line(&format!("- name: {param_name}"));
    w.indent();
    w.line(&format!("in: {location}"));
    w.line(&format!("required: {required}"));
    w.line("schema:");
    w.indent();
    match field {
        Some(f) => write_field_type_schema(w, f),
        None => w.line("type: string"),
    }
    w.dedent();
    w.dedent();
}

/// The `responses` block — the output message schema as `200`. Net-zero on the
/// writer's depth (5 indents, 5 dedents), so a caller that entered at the
/// operation-body level (`post:`/`get:`/…) is returned to exactly that level.
fn emit_ok_response(w: &mut YamlWriter, method: &IrMethod) {
    w.line("responses:");
    w.indent();
    w.line("'200':");
    w.indent();
    w.line(&format!("description: {} response.", method.name));
    w.line("content:");
    w.indent();
    w.line("application/json:");
    w.indent();
    w.line("schema:");
    w.indent();
    w.line(&format!(
        "$ref: '#/components/schemas/{}'",
        method.output.mojo_name
    ));
    w.dedent();
    w.dedent();
    w.dedent();
    w.dedent();
    w.dedent();
}

/// A streaming-mode token for the operation summary.
fn streaming_token(m: &IrMethod) -> &'static str {
    match (m.client_streaming, m.server_streaming) {
        (false, false) => "unary",
        (false, true) => "server-streaming",
        (true, false) => "client-streaming",
        (true, true) => "bidirectional-streaming",
    }
}

/// An `IrEnum` as an OpenAPI Schema Object — a string enum (the proto3
/// JSON enum representation: enum values serialise as their NAME).
fn emit_enum_schema(w: &mut YamlWriter, en: &IrEnum) {
    w.line(&format!("{}:", en.mojo_name));
    w.indent();
    w.line("type: string");
    w.line(&format!("description: proto enum {}.", en.fq_name));
    w.line("enum:");
    for v in &en.values {
        w.line(&format!("  - {}", v.name));
    }
    w.dedent();
}

/// An `IrMessage` as an OpenAPI Schema Object — `type: object` with one
/// property per field. proto3 has no required fields, so no `required:`
/// list is written (the proto3-JSON contract: every field is optional).
fn emit_message_schema(w: &mut YamlWriter, msg: &IrMessage) {
    w.line(&format!("{}:", msg.mojo_name));
    w.indent();
    w.line("type: object");
    w.line(&format!("description: proto message {}.", msg.fq_name));

    let has_props = !msg.fields.is_empty();
    if has_props {
        w.line("properties:");
        w.indent();
        // Non-oneof fields, keyed by the proto3 JSON name (the wire key
        // the JSON projection uses).
        for field in &msg.fields {
            if field.oneof_index.is_some() {
                continue;
            }
            emit_field_property(w, field);
        }
        // oneof arms — OpenAPI 3.0 has no native discriminated union at
        // the property level; each arm renders as its own optional
        // property (matching how proto3-JSON serialises a oneof: exactly
        // one arm key is present). A comment records the oneof grouping.
        for oneof in &msg.oneofs {
            w.line(&format!("# oneof '{}' — at most one arm is set", oneof.name));
            for arm in &oneof.arms {
                if let Some(field) = msg.fields.iter().find(|f| &f.name == arm) {
                    emit_field_property(w, field);
                }
            }
        }
        w.dedent();
    } else {
        // An empty message — a valid empty object schema.
        w.line("properties: {}");
    }
    w.dedent();
}

fn emit_stub_schema(w: &mut YamlWriter, mojo_name: &str) {
    w.line(&format!("{mojo_name}:"));
    w.indent();
    w.line("type: object");
    w.line(&format!(
        "description: cross-file type {mojo_name} (declared in an imported .proto)."
    ));
    w.dedent();
}

fn referenced_but_absent(model: &IrModel, emitted: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut consider = |name: &str, out: &mut Vec<String>| {
        if !emitted.iter().any(|e| e == name) && !out.iter().any(|o| o == name) {
            out.push(name.to_string());
        }
    };
    for file in &model.files {
        for msg in &file.messages {
            if msg.is_map_entry {
                continue;
            }
            for field in &msg.fields {
                collect_type_refs(&field.ty, &mut |n| consider(n, &mut out));
            }
        }
    }
    out
}

/// Invoke `f` with the `mojo_name` of every message/enum reference reachable in
/// `ty` (unwrapping map value + nested map types).
fn collect_type_refs(ty: &IrType, f: &mut impl FnMut(&str)) {
    match ty {
        IrType::Message(r) | IrType::Enum(r) => f(&r.mojo_name),
        IrType::Scalar(_) => {}
        IrType::Map(k, v) => {
            collect_type_refs(k, f);
            collect_type_refs(v, f);
        }
        IrType::List(_) => unreachable!("{}", crate::ir::LIST_IS_AWS_FRONT_END_ONLY),
    }
}

/// One field as a `properties` entry, keyed by `json_name`.
fn emit_field_property(w: &mut YamlWriter, field: &IrField) {
    w.line(&format!("{}:", field.json_name));
    w.indent();
    write_field_type_schema(w, field);
    w.dedent();
}

/// Write the schema BODY (the `type:` / `items:` / `additionalProperties:` /
/// `$ref:` lines) for one field, honoring its label — a `repeated` field is an
/// `array`, a `map<K,V>` field is an object with `additionalProperties`, a
/// singular field is its bare type schema. Shared by the message `properties`
/// projection AND the REST path/query-parameter + named-body projections, so a
/// field's OpenAPI schema is written ONE way everywhere.
fn write_field_type_schema(w: &mut YamlWriter, field: &IrField) {
    match &field.ty {
        IrType::Map(_, v) => {
            // proto3 `map<K,V>` -> a JSON object with arbitrary string
            // keys (proto3-JSON renders every map key as a string).
            w.line("type: object");
            w.line("additionalProperties:");
            w.indent();
            write_type_schema(w, v);
            w.dedent();
        }
        _ if field.label == Label::Repeated => {
            w.line("type: array");
            w.line("items:");
            w.indent();
            write_type_schema(w, &field.ty);
            w.dedent();
        }
        _ => {
            write_type_schema(w, &field.ty);
        }
    }
}

/// Write the `type:` / `$ref:` lines for a single (label-stripped) IR
/// type. A scalar becomes an OpenAPI primitive + `format`; a message /
/// enum becomes a `$ref` into `components/schemas`.
fn write_type_schema(w: &mut YamlWriter, ty: &IrType) {
    match ty {
        IrType::Scalar(s) => {
            let (t, fmt) = openapi_scalar(*s);
            w.line(&format!("type: {t}"));
            if let Some(fmt) = fmt {
                w.line(&format!("format: {fmt}"));
            }
        }
        IrType::Message(r) => {
            w.line(&format!("$ref: '#/components/schemas/{}'", r.mojo_name));
        }
        IrType::Enum(r) => {
            w.line(&format!("$ref: '#/components/schemas/{}'", r.mojo_name));
        }
        IrType::Map(_, v) => {
            // A nested map (map value is itself a map) — render as an
            // object with typed additionalProperties.
            w.line("type: object");
            w.line("additionalProperties:");
            w.indent();
            write_type_schema(w, v);
            w.dedent();
        }
        IrType::List(_) => unreachable!("{}", crate::ir::LIST_IS_AWS_FRONT_END_ONLY),
    }
}

/// The OpenAPI `(type, format)` pair for a proto scalar. The proto3-JSON
/// mapping serialises 64-bit integers as STRINGS (to survive a JSON
/// number's 53-bit mantissa) — so `int64`/`uint64` map to `type: string`
/// with a numeric `format`, exactly as gnostic and `protoc-gen-openapi`
/// do.
fn openapi_scalar(s: ScalarKind) -> (&'static str, Option<&'static str>) {
    match s {
        ScalarKind::Double => ("number", Some("double")),
        ScalarKind::Float => ("number", Some("float")),
        ScalarKind::Int64 => ("string", Some("int64")),
        ScalarKind::Uint64 => ("string", Some("uint64")),
        ScalarKind::Sint64 => ("string", Some("int64")),
        ScalarKind::Sfixed64 => ("string", Some("int64")),
        ScalarKind::Fixed64 => ("string", Some("uint64")),
        ScalarKind::Int32 => ("integer", Some("int32")),
        ScalarKind::Uint32 => ("integer", Some("int64")),
        ScalarKind::Sint32 => ("integer", Some("int32")),
        ScalarKind::Sfixed32 => ("integer", Some("int32")),
        ScalarKind::Fixed32 => ("integer", Some("int64")),
        ScalarKind::Bool => ("boolean", None),
        ScalarKind::String => ("string", None),
        ScalarKind::Bytes => ("string", Some("byte")),
    }
}


struct YamlWriter {
    buf: String,
    depth: usize,
}

impl YamlWriter {
    fn new() -> Self {
        Self { buf: String::new(), depth: 0 }
    }

    fn indent(&mut self) {
        self.depth += 1;
    }

    fn dedent(&mut self) {
        self.depth = self.depth.saturating_sub(1);
    }

    /// Append one line at the current indentation depth (2-space units).
    fn line(&mut self, text: &str) {
        for _ in 0..self.depth {
            self.buf.push_str("  ");
        }
        self.buf.push_str(text);
        self.buf.push('\n');
    }

    /// Splice another writer's buffer in verbatim (it has already been
    /// emitted at the right depth via its own `indent()` calls).
    fn append(&mut self, other: &YamlWriter) {
        self.buf.push_str(&other.buf);
    }

    fn finish(self) -> String {
        self.buf
    }
}

/// Emit a `CodeGeneratorResponse`-style file list for the OpenAPI plugin
/// — one file, `openapi.yaml`.
pub fn emit_openapi_files(model: &IrModel) -> Vec<(String, String)> {
    let mut doc = emit_openapi(model);
    // The `Write` import keeps the file's idiom consistent with `emit.rs`;
    // a trailing newline is guaranteed by `YamlWriter::line`.
    let _ = write!(doc, "");
    vec![("openapi.yaml".to_string(), doc)]
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A one-method model: `Req { string name }`, served at `path` by GET.
    fn model(path: &str) -> IrModel {
        let ty = TypeRef { fq_name: ".t.v1.Req".into(), mojo_name: "Req".into() };
        let svc = IrService {
            name: "S".into(),
            default_host: None,
            host_from_service_config: false,
            methods: vec![IrMethod {
                name: "M".into(),
                input: ty.clone(),
                output: ty,
                client_streaming: false,
                server_streaming: false,
                idempotent: false,
                http_rule: Some(IrHttpRule {
                    verb: "get".into(),
                    path_template: path.into(),
                    body: String::new(),
                    additional_bindings: vec![],
                }),
                routing_rule: None,
            }],
        };
        IrModel {
            files: vec![IrFile {
                proto_path: "t.proto".into(),
                proto_package: "t.v1".into(),
                mojo_package: "t".into(),
                messages: vec![IrMessage {
                    name: "Req".into(),
                    mojo_name: "Req".into(),
                    fq_name: ".t.v1.Req".into(),
                    is_map_entry: false,
                    fields: vec![IrField {
                        name: "name".into(),
                        ty: IrType::Scalar(ScalarKind::String),
                        label: Label::Single,
                        proto_field_number: 1,
                        json_name: "name".into(),
                        oneof_index: None,
                    }],
                    oneofs: vec![],
                }],
                enums: vec![],
                services: vec![svc],
                imports: vec![],
            }],
        }
    }

    #[test]
    fn plain_capture_is_a_path_parameter() {
        let doc = emit_openapi(&model("/v1/{name}/things"));
        assert!(doc.contains("/v1/{name}/things:"), "{doc}");
        assert!(doc.contains("in: path"), "{doc}");
    }

    #[test]
    fn written_pattern_keeps_the_whole_body_projection() {
        // The path key is the template text, which has no `{name}`
        // placeholder for an `in: path` parameter called `name` to fill:
        // `{name=*}` (one segment, like `{name}`) included.
        for path in ["/v1/{name=*}/things", "/v1/{name=projects/*}/things"] {
            let doc = emit_openapi(&model(path));
            assert!(!doc.contains("in: path"), "{path}: {doc}");
            assert!(doc.contains("requestBody:"), "{path}: {doc}");
        }
    }

    #[test]
    fn each_additional_binding_is_an_operation_at_its_own_path() {
        let mut m = model("/v1/{name}/things");
        let rule = m.files[0].services[0].methods[0].http_rule.as_mut().unwrap();
        for path in ["/v1/orgs/{name}/things", "/v1/projects/{name}/things"] {
            rule.additional_bindings.push(IrHttpRule {
                verb: "get".into(),
                path_template: path.into(),
                body: String::new(),
                additional_bindings: vec![],
            });
        }
        let doc = emit_openapi(&m);
        let first = doc.find("/v1/{name}/things:").expect("the rule's path");
        let second = doc.find("/v1/orgs/{name}/things:").expect("the first binding's path");
        let third = doc.find("/v1/projects/{name}/things:").expect("the second binding's path");
        assert!(first < second && second < third, "{doc}");
        assert_eq!(doc.matches("operationId: S_M\n").count(), 1, "{doc}");
        assert_eq!(doc.matches("operationId: S_M_2\n").count(), 1, "{doc}");
        assert_eq!(doc.matches("operationId: S_M_3\n").count(), 1, "{doc}");
        assert_eq!(doc.matches("in: path").count(), 3, "{doc}");
    }
}
