//! `mojo-gen-openapi`: reads an OpenAPI v3 document and emits a Mojo client
//! through the same emitter the `.proto` path uses.

use std::io::Write;
use std::path::Path;
use std::process::ExitCode;

use komira_proto_codegen::generate_from_openapi;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().collect();
    if args.len() < 3 {
        eprintln!(
            "usage: {} <openapi-doc> <out-dir> [package_prefix]",
            args.first().map(String::as_str).unwrap_or("mojo-gen-openapi")
        );
        return ExitCode::FAILURE;
    }
    let doc_path = &args[1];
    let out_dir = &args[2];
    let package_prefix = args.get(3).map(String::as_str).unwrap_or("komira_rpc_storage");

    let doc_text = match std::fs::read_to_string(doc_path) {
        Ok(t) => t,
        Err(e) => {
            eprintln!("mojo-gen-openapi: cannot read {doc_path}: {e}");
            return ExitCode::FAILURE;
        }
    };

    let (files, notes) =
        match generate_from_openapi(&doc_text, doc_path, package_prefix) {
            Ok(out) => out,
            Err(e) => {
                eprintln!("mojo-gen-openapi: {e}");
                return ExitCode::FAILURE;
            }
        };

    // The package `__init__.mojo` — the codegen output is a flat,
    // single-level Mojo package; an `__init__.mojo` makes a downstream
    // `mojo_library` able to locate the package dir (same shape as
    // `mojo_proto_library`'s emitted `__init__.mojo`).
    if let Err(e) = write_file(
        Path::new(out_dir).join("__init__.mojo"),
        "# GENERATED by mojo-gen-openapi — the OpenAPI-input package \
         facade.\n# Do not hand-edit.\n",
    ) {
        eprintln!("mojo-gen-openapi: {e}");
        return ExitCode::FAILURE;
    }

    for (name, content) in &files {
        if let Err(e) = write_file(Path::new(out_dir).join(name), content) {
            eprintln!("mojo-gen-openapi: {e}");
            return ExitCode::FAILURE;
        }
    }

    for note in &notes {
        eprintln!("mojo-gen-openapi note: {note}");
    }
    ExitCode::SUCCESS
}

/// Write `content` to `path`, creating parent directories as needed.
fn write_file(path: std::path::PathBuf, content: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
    }
    let mut f = std::fs::File::create(&path)
        .map_err(|e| format!("cannot create {}: {e}", path.display()))?;
    f.write_all(content.as_bytes())
        .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(())
}
