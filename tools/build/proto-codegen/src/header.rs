//! The header of every generated Mojo file.
//!
//! The first line carries [`GENERATED_TOKEN`] and names the generator; the
//! lines after it pin each input by name and sha256; the last says not to
//! edit the file and how to regenerate it. A tool that must tell a generated
//! file from a hand-written one (the coverage floors, the regenerate-and-diff
//! gate) matches the token on the first line, so every emitter writes its
//! header through [`render`] and none spells the token itself.
//!
//! The text depends on nothing but its arguments: no path of the host or of
//! the build root, no time, no user.

/// What the first line of a generated file contains.
pub const GENERATED_TOKEN: &str = "@generated";

/// How to regenerate a file. The one place this text is written for the
/// generators in this crate; the package `__init__.mojo` of the Zig rule
/// actions repeat it (`tools/build/mojo/tools/proto_gen.zig`,
/// `tools/build/cloud/aws_act.zig`), and a test of each holds them equal.
pub const REGEN_COMMAND: &str = "buck2 run //tools/build/proto-codegen:regen -- <target>";

/// The generator version of the `protoc-gen-mojo` family (`protoc-gen-mojo`,
/// `-db`, `-routes` and the OpenAPI front-end). Bump it when the text emitted
/// for the same inputs changes, as `emit_aws::AWS_GENERATOR_VERSION` is for
/// `aws-client-gen`.
pub const PLUGIN_GENERATOR_VERSION: &str = "1";

/// One input of a generated file: its name as the generator was given it
/// (a proto import path, a botocore model key, a file name; never an absolute
/// path) and the sha256 of its bytes.
#[derive(Clone, Copy, Debug)]
pub struct Pin<'a> {
    pub name: &'a str,
    pub sha256: &'a str,
}

/// The header lines of a file generated by `generator` at `version` from
/// `pins`, each ending in a newline:
///
/// ```text
/// # @generated by protoc-gen-mojo version 1
/// # input example/v1/thing.proto sha256:<64 hex digits>
/// # DO NOT EDIT. Regenerate with: buck2 run //tools/build/proto-codegen:regen -- <target>
/// ```
///
/// An input with no digest (hand-built IR in a test) is written as
/// `sha256:unpinned`.
pub fn render(generator: &str, version: &str, pins: &[Pin<'_>]) -> String {
    let mut out = format!("# {GENERATED_TOKEN} by {generator} version {version}\n");
    for p in pins {
        let digest = if p.sha256.is_empty() { "unpinned" } else { p.sha256 };
        out.push_str(&format!("# input {} sha256:{digest}\n", p.name));
    }
    out.push_str(&format!("# DO NOT EDIT. Regenerate with: {REGEN_COMMAND}\n"));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_first_line_names_the_token_and_the_generator() {
        let h = render("protoc-gen-mojo", "1", &[]);
        assert_eq!(h.lines().next(), Some("# @generated by protoc-gen-mojo version 1"));
    }

    #[test]
    fn the_first_line_starts_with_hash_space_token_space() {
        let h = render("g", "1", &[]);
        assert!(h.starts_with("# @generated "), "{h}");
        assert_eq!(GENERATED_TOKEN, "@generated");
    }

    #[test]
    fn each_input_is_one_line_in_the_order_given() {
        let h = render(
            "g",
            "2",
            &[
                Pin { name: "b.proto", sha256: "bb" },
                Pin { name: "a.proto", sha256: "aa" },
            ],
        );
        let lines: Vec<&str> = h.lines().collect();
        assert_eq!(lines[1], "# input b.proto sha256:bb");
        assert_eq!(lines[2], "# input a.proto sha256:aa");
        assert_eq!(lines.len(), 4);
    }

    #[test]
    fn the_last_line_says_do_not_edit_and_how_to_regenerate() {
        let h = render("g", "1", &[]);
        assert_eq!(
            h.lines().last(),
            Some("# DO NOT EDIT. Regenerate with: buck2 run //tools/build/proto-codegen:regen -- <target>")
        );
        assert!(h.ends_with('\n'));
    }

    #[test]
    fn an_input_with_no_digest_is_said_so() {
        let h = render("g", "1", &[Pin { name: "x.proto", sha256: "" }]);
        assert!(h.contains("# input x.proto sha256:unpinned\n"));
    }
}
