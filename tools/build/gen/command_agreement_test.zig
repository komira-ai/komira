//! The regenerate command is one text, spelled in four places: `REGEN_COMMAND` of
//! defs.bzl (the failure message of `<name>_fresh` prints it before the library's
//! label), the header constant of the Rust crate, and the `__init__.mojo` text of
//! the two Zig rule actions (each with `<library target>` after it). Each is read
//! from its file here; none is copied into this test, so a change to one alone
//! fails.
const std = @import("std");
const t = std.testing;

fn readTree(path: []const u8) ![]u8 {
    const work = try std.process.getEnvVarOwned(t.allocator, "KOMIRA_TEST_WORK");
    defer t.allocator.free(work);
    var dir = try std.fs.openDirAbsolute(work, .{});
    defer dir.close();
    return dir.readFileAlloc(t.allocator, path, 1 << 24);
}

/// The text between the quotes of defs.bzl's `REGEN_COMMAND = "..."`, which is its
/// only definition.
fn command(defs: []const u8) ![]const u8 {
    const key = "\nREGEN_COMMAND = \"";
    try t.expectEqual(@as(usize, 1), std.mem.count(u8, defs, key));
    const start = std.mem.indexOf(u8, defs, key).? + key.len;
    const end = std.mem.indexOfPos(u8, defs, start, "\"").?;
    return defs[start..end];
}

fn spelled(a: std.mem.Allocator, cmd: []const u8) ![]u8 {
    return std.fmt.allocPrint(a, "Regenerate with `{s} <library target>`. Generated by", .{cmd});
}

test "the command is a buck2 run of the regen target" {
    const defs = try readTree("gen/tools/build/gen/defs.bzl");
    defer t.allocator.free(defs);
    try t.expectEqualStrings("./buck2 run komira//tools/build/gen:regen --", try command(defs));
}

test "the Rust header constant spells defs.bzl's command" {
    const defs = try readTree("gen/tools/build/gen/defs.bzl");
    defer t.allocator.free(defs);
    const header = try readTree("proto-codegen/tools/build/proto-codegen/src/header.rs");
    defer t.allocator.free(header);
    const want = try spelled(t.allocator, try command(defs));
    defer t.allocator.free(want);
    const key = "pub const DO_NOT_EDIT: &str = \"DO NOT EDIT. ";
    const at = std.mem.indexOf(u8, header, key) orelse return error.NoConstant;
    try t.expect(std.mem.startsWith(u8, header[at + key.len ..], want));
}

test "each Zig rule action writes the same command into its __init__.mojo" {
    const defs = try readTree("gen/tools/build/gen/defs.bzl");
    defer t.allocator.free(defs);
    const want = try spelled(t.allocator, try command(defs));
    defer t.allocator.free(want);
    const aws = try readTree("cloud/tools/build/cloud/aws_act.zig");
    defer t.allocator.free(aws);
    const proto = try readTree("mojo/tools/build/mojo/tools/proto_gen.zig");
    defer t.allocator.free(proto);
    const key = "# DO NOT EDIT. ";
    for ([_][]const u8{ aws, proto }) |src| {
        var found: usize = 0;
        var from: usize = 0;
        while (std.mem.indexOfPos(u8, src, from, key)) |at| : (from = at + key.len) {
            if (std.mem.startsWith(u8, src[at + key.len ..], want)) found += 1;
        }
        try t.expectEqual(@as(usize, 1), found);
    }
}
