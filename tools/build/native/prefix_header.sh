#!/bin/sh
# A vendored C library's prefix header (README.md), written by a build action
# of a `prefix_header` target (defs.bzl):
#   sh prefix_header.sh <busybox> <elfsyms> <lib.a> <header> <symbols> <style> <prefix> <strip> <min> [<extra>...]
# <symbols> is every name the header renames, one per line: the defined
# global symbols of <lib.a> (its archive symbol table) and each <extra> (a
# name the library references but does not define, such as a weak hook),
# less aws-lc's util/read_symbols.go skip list and __umodti3 (a compiler
# builtin: the compiler calls it by that name, so it cannot be renamed).
# <header> defines each name to its prefixed form:
#   boringssl  aws-lc's own boringssl_prefix_symbols.h: X -> <prefix>_X
#   strip      X -> <prefix><X less <strip>> when X starts with <strip>,
#              else <prefix>_X (so every name starts with <prefix>)
# Fewer than <min> names is an error: an empty or wrong archive must not give
# a header that renames nothing.
set -eu
# shellcheck disable=SC3040 # busybox sh (ash) has pipefail
set -o pipefail

abs() { case "$1" in /*) printf '%s' "$1" ;; *) printf '%s/%s' "$PWD" "$1" ;; esac; }
BB=$(abs "$1")
TOOL=$(abs "$2")
ARCHIVE=$(abs "$3")
HDR=$(abs "$4")
SYMS=$(abs "$5")
STYLE=$6
PREFIX=$7
STRIP=$8
MIN=$9
shift 9

# Private scratch (as in tools/build/mojo/toolchain.bzl): a local action runs
# in the checkout root, so it takes the directory buck2 names for it.
case "${BUCK_SCRATCH_PATH:-}" in
    "") T="$PWD/.prefix_header" ;;
    /*) T="$BUCK_SCRATCH_PATH/prefix_header" ;;
    *) T="$PWD/$BUCK_SCRATCH_PATH/prefix_header" ;;
esac
"$BB" mkdir -p "$T/bin"
"$BB" --install -s "$T/bin"
PATH="$T/bin"
export PATH LC_ALL=C

"$TOOL" armap "$ARCHIVE" > "$T/armap.txt"
for x in "$@"; do
    echo "$x"
done > "$T/extra.txt"
sort -u "$T/armap.txt" "$T/extra.txt" |
    grep -v -E '^(_Z|__x86\.get_pc_thunk\.|__real@)' |
    grep -v -x -E '__local_stdio_printf_options|__local_stdio_scanf_options|_vscprintf|_vscprintf_l|_vsscanf_l|_xmm|sscanf|vsnprintf|sdallocx|__umodti3' \
        > "$SYMS"
n=$(wc -l < "$SYMS")
if [ "$n" -lt "$MIN" ]; then
    echo "prefix_header: only $n names read from $ARCHIVE (at least $MIN expected)" >&2
    exit 1
fi

case "$STYLE" in
    boringssl)
        {
            echo "/* Generated by komira//tools/build/native (prefix_header.sh): aws-lc's"
            echo "   boringssl_prefix_symbols.h for the prefix $PREFIX, $n names. */"
            echo "#ifndef BORINGSSL_PREFIX_SYMBOLS_H"
            echo "#define BORINGSSL_PREFIX_SYMBOLS_H"
            echo "#ifndef BORINGSSL_PREFIX"
            echo "#define BORINGSSL_PREFIX $PREFIX"
            echo "#endif"
            echo "#define BORINGSSL_ADD_PREFIX(a, b) BORINGSSL_ADD_PREFIX_INNER(a, b)"
            echo "#define BORINGSSL_ADD_PREFIX_INNER(a, b) a ## _ ## b"
            sed 's/.*/#define & BORINGSSL_ADD_PREFIX(BORINGSSL_PREFIX, &)/' "$SYMS"
            echo "#endif"
        } > "$HDR"
        ;;
    strip)
        [ -n "$STRIP" ] || { echo "prefix_header: style strip needs a non-empty strip" >&2; exit 1; }
        guard=KOMIRA_PREFIX_$(printf '%s' "$PREFIX" | tr 'a-z' 'A-Z' | tr -c 'A-Z0-9' '_')H
        {
            echo "/* Generated by komira//tools/build/native (prefix_header.sh): $n names,"
            echo "   each renamed to start with $PREFIX. */"
            echo "#ifndef $guard"
            echo "#define $guard"
            awk -v p="$PREFIX" -v s="$STRIP" '{
                if (index($0, s) == 1) print "#define " $0 " " p substr($0, length(s) + 1)
                else print "#define " $0 " " p "_" $0
            }' "$SYMS"
            echo "#endif"
        } > "$HDR"
        ;;
    *)
        echo "prefix_header: unknown style $STYLE" >&2
        exit 1
        ;;
esac
