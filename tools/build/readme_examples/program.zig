//! The programs that run a README's examples, and their line map. Pure: no
//! I/O.
//!
//! Each example is a program of its own, `readme_<package>_<line>.mojo`,
//! `<line>` being the README line of its opening fence: two examples never
//! share a module, so they may declare the same names and import the same
//! ones, and a failure names exactly one example. The fence tag is the mode,
//! and nothing is inferred from the code:
//!
//! - ```mojo: the example's lines are pasted as they are, each indented four
//!   spaces, into `def main() raises:`. Mojo allows an import inside a
//!   function, so nothing is hoisted and no line is read as a statement. A
//!   `pass` follows when no line holds code (blank lines and comments only).
//! - ```mojo module: the example's lines are the whole program, copied as
//!   they are; it declares its own `main`.
//!
//! Hidden lines (examples.zig) are part of the example in either mode.
//!
//! Every copied line sits on the line it has in the README: line n of the
//! program is line n of the README (the lines before and between are blank;
//! the first holds a comment naming the README, and in a ```mojo example the
//! line just before the first copied line holds `def main() raises:`). So a
//! compile error or an assertion's `readme_<package>_<line>.mojo:<n>` names
//! README line n, and `mapReport` rewrites it to `<readme>:<n>`.
//!
//! The runner, `readme_<package>.mojo`, imports each example's program as a
//! module beside it and calls its `main` inside `try`, in README order; a
//! failure prints `<readme>:<line>: FAILED: <error>` and the run continues.
//! Then it prints `readme_<package> validation: P of E checks passed` (one
//! check per example: the line kci's read-back parses) and raises if any
//! failed. With no example it prints that it ran nothing. The build runs
//! each example's program on its own (`[tests][readme]`); the runner is what
//! a single run of every example (a coverage build, an installed README's
//! validation) compiles.

const std = @import("std");
const md = @import("markdown");
const Example = @import("examples.zig").Example;
const Allocator = std.mem.Allocator;

pub const GENERATED = "# Generated by //tools/build/readme_examples from ";

/// A program that cannot be generated: `msg` says why, naming the README
/// line of its example.
pub const Error = Allocator.Error || error{Refused};

pub const Program = struct {
    /// The file name: exampleName's, or programName's for the runner.
    name: []const u8,
    text: []const u8,
};

/// `readme_<package>.mojo`, the runner. Never `<package>.mojo`: a file next
/// to the program named like the package would be an import root shadowing
/// it.
pub fn programName(alloc: Allocator, package: []const u8) Allocator.Error![]const u8 {
    return std.fmt.allocPrint(alloc, "readme_{s}.mojo", .{package});
}

/// `readme_<package>_<line>`: the module of the example whose opening fence
/// is README line `line`.
pub fn exampleModule(alloc: Allocator, package: []const u8, line: usize) Allocator.Error![]const u8 {
    return std.fmt.allocPrint(alloc, "readme_{s}_{d}", .{ package, line });
}

/// `readme_<package>_<line>.mojo`, the example's program.
pub fn exampleName(alloc: Allocator, package: []const u8, line: usize) Allocator.Error![]const u8 {
    return std.fmt.allocPrint(alloc, "readme_{s}_{d}.mojo", .{ package, line });
}

fn isBlank(s: []const u8) bool {
    return md.indentOf(s) == s.len;
}

/// Whether a line holds code: not blank and not a comment.
fn holdsCode(lines: []const []const u8) bool {
    for (lines) |l| {
        const t = md.strip(l);
        if (t.len > 0 and t[0] != '#') return true;
    }
    return false;
}

/// The program of example `ex` of README `display` (file header): line n of
/// it is line n of the README. error.Refused sets `msg.*`.
pub fn exampleProgram(alloc: Allocator, ex: Example, display: []const u8, msg: *[]const u8) Error![]const u8 {
    const first = if (ex.code.len > 0) ex.code_lines[0] else ex.line + 1;
    // The line `def main() raises:` takes in a ```mojo example.
    const main_line: usize = if (ex.module) 0 else first - 1;
    if (!ex.module and main_line < 1) {
        msg.* = try std.fmt.allocPrint(alloc, "{s}:{d}: the example's first line is README line 1, which leaves no line for its `def main`", .{ display, ex.line });
        return error.Refused;
    }
    var out = std.ArrayList([]const u8).init(alloc);
    const header_room = (if (ex.module) first else main_line) - 1;
    if (header_room >= 1) {
        try out.append(try std.fmt.allocPrint(alloc, GENERATED ++ "{s}, the example at line {d}. Do not edit: line n is README line n.", .{ display, ex.line }));
    }
    while (out.items.len + 1 < main_line) try out.append("");
    if (!ex.module) try out.append("def main() raises:");
    for (ex.code, ex.code_lines) |line, n| {
        if (n <= out.items.len) {
            msg.* = try std.fmt.allocPrint(alloc, "{s}:{d}: README line {d} is copied out of order", .{ display, ex.line, n });
            return error.Refused;
        }
        while (out.items.len < n - 1) try out.append("");
        if (isBlank(line)) {
            try out.append("");
        } else if (ex.module) {
            try out.append(line);
        } else {
            try out.append(try std.mem.concat(alloc, u8, &.{ "    ", line }));
        }
    }
    if (!ex.module and !holdsCode(ex.code)) try out.append("    pass");
    var text = std.ArrayList(u8).init(alloc);
    for (out.items) |l| {
        try text.appendSlice(l);
        try text.append('\n');
    }
    return text.toOwnedSlice();
}

/// Every program of package `package`'s README `display`: one per example,
/// in README order, each made from that example alone, then the runner (file
/// header). error.Refused sets `msg.*`.
pub fn generatePrograms(alloc: Allocator, examples: []const Example, package: []const u8, display: []const u8, msg: *[]const u8) Error![]const Program {
    var out = std.ArrayList(Program).init(alloc);
    for (examples) |ex| {
        try out.append(.{ .name = try exampleName(alloc, package, ex.line), .text = try exampleProgram(alloc, ex, display, msg) });
    }
    try out.append(.{ .name = try programName(alloc, package), .text = try runnerProgram(alloc, examples, package, display) });
    return out.toOwnedSlice();
}

/// `s` as a double-quoted Mojo string literal.
pub fn mojoStringLiteral(alloc: Allocator, s: []const u8) Allocator.Error![]const u8 {
    var out = std.ArrayList(u8).init(alloc);
    try out.append('"');
    for (s) |c| {
        switch (c) {
            '"' => try out.appendSlice("\\\""),
            '\\' => try out.appendSlice("\\\\"),
            '\n' => try out.appendSlice("\\n"),
            else => try out.append(c),
        }
    }
    try out.append('"');
    return out.toOwnedSlice();
}

/// The runner of the examples of package `package`'s README, named
/// `display` in its messages (file header).
pub fn runnerProgram(alloc: Allocator, examples: []const Example, package: []const u8, display: []const u8) Allocator.Error![]const u8 {
    var out = std.ArrayList(u8).init(alloc);
    const w = out.writer();
    try w.print(GENERATED ++ "{s}. Do not edit: it runs each example's program, beside it.\n", .{display});
    if (examples.len == 0) {
        const none = try std.fmt.allocPrint(alloc, "NO EXAMPLE: {s} holds no ```mojo example", .{display});
        try w.print("\n\ndef main():\n    print({s})\n", .{try mojoStringLiteral(alloc, none)});
        return out.toOwnedSlice();
    }
    try w.writeAll("\n");
    for (examples) |ex| try w.print("import {s}\n", .{try exampleModule(alloc, package, ex.line)});
    try w.writeAll("\n\ndef main() raises:\n    var failed = 0\n");
    for (examples) |ex| {
        try w.print("    try:\n        {s}.main()\n    except e:\n        failed += 1\n", .{try exampleModule(alloc, package, ex.line)});
        const failed = try std.fmt.allocPrint(alloc, "{s}:{d}: FAILED: ", .{ display, ex.line });
        try w.print("        print({s} + String(e))\n", .{try mojoStringLiteral(alloc, failed)});
    }
    const total = examples.len;
    const head = try std.fmt.allocPrint(alloc, "readme_{s} validation: ", .{package});
    const tail = try std.fmt.allocPrint(alloc, " of {d} checks passed", .{total});
    try w.print("    print({s} + String({d} - failed) + {s})\n", .{ try mojoStringLiteral(alloc, head), total, try mojoStringLiteral(alloc, tail) });
    try w.writeAll("    if failed > 0:\n");
    const failed = try std.fmt.allocPrint(alloc, " of {d} README examples failed", .{total});
    try w.print("        raise Error(String(failed) + {s})\n", .{try mojoStringLiteral(alloc, failed)});
    return out.toOwnedSlice();
}

fn digitsFrom(s: []const u8, start: usize) usize {
    var k = start;
    while (k < s.len and std.ascii.isDigit(s[k])) k += 1;
    return k;
}

/// `report` with every `[<dir>/]readme_<package>_<line>.mojo:<n>` (an
/// example's program) rewritten to `<display>:<n>`: the program's line n is
/// README line n. The runner's own lines are left as they are.
pub fn mapReport(alloc: Allocator, report: []const u8, package: []const u8, display: []const u8) Allocator.Error![]const u8 {
    const stem = try std.fmt.allocPrint(alloc, "readme_{s}_", .{package});
    const ext = ".mojo:";
    var out = std.ArrayList(u8).init(alloc);
    var i: usize = 0;
    var start: usize = 0;
    while (i < report.len) {
        const at = std.mem.indexOfPos(u8, report, i, stem) orelse break;
        const j = at + stem.len;
        const k = digitsFrom(report, j);
        if (k == j or !std.mem.startsWith(u8, report[k..], ext)) {
            i = j;
            continue;
        }
        const d = k + ext.len;
        const e = digitsFrom(report, d);
        if (e == d) {
            i = j;
            continue;
        }
        // The whole path token: back to whitespace, a quote, a bracket or the line start.
        var p = at;
        while (p > 0) : (p -= 1) {
            const c = report[p - 1];
            if (c == ' ' or c == '\t' or c == '\n' or c == '"' or c == '\'' or c == '(') break;
        }
        // `readme_<package>_` must start the file name, not end another one.
        if (at > p and report[at - 1] != '/') {
            i = j;
            continue;
        }
        if (p > start) try out.appendSlice(report[start..p]);
        try out.appendSlice(display);
        try out.append(':');
        try out.appendSlice(report[d..e]);
        start = e;
        i = e;
    }
    try out.appendSlice(report[start..]);
    return out.toOwnedSlice();
}
