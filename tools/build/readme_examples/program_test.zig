//! The generated programs, byte for byte: one per example, in the mode its
//! fence names, every copied line on its README line; the runner; the line
//! map.

const std = @import("std");
const ex = @import("examples.zig");
const prog = @import("program.zig");
const t = std.testing;

const Arena = std.heap.ArenaAllocator;

const README =
    \\# P
    \\
    \\<!-- mojo-hidden from std.testing import assert_equal -->
    \\```mojo
    \\from pkg import f
    \\
    \\def g(x: Int) -> Int:
    \\    return f(x)
    \\
    \\assert_equal(g(1), 2)
    \\```
    \\
    \\```mojo module
    \\from pkg import f
    \\
    \\
    \\@fieldwise_init
    \\struct P(Copyable):
    \\    var x: Int
    \\
    \\
    \\def main():
    \\    print(f(P(1).x))
    \\```
    \\<!-- mojo-hidden
    \\comptime S = """a
    \\  b"""
    \\-->
    \\
;

// A ```mojo example: `def main() raises:` on the line before its first
// copied line (the hidden import, README line 3), then every line pasted as
// it is and indented, on its README line. The import stays where it is
// (inside main), and the nested `def g` is not hoisted.
const GOLDEN_4 =
    \\# Generated by //tools/build/readme_examples from R.md, the example at line 4. Do not edit: line n is README line n.
    \\def main() raises:
    \\    from std.testing import assert_equal
    \\
    \\    from pkg import f
    \\
    \\    def g(x: Int) -> Int:
    \\        return f(x)
    \\
    \\    assert_equal(g(1), 2)
    \\
;

// A ```mojo module example: copied as it is, hidden lines after it included
// (a triple-quoted string untouched), on its README lines; no main is added.
const GOLDEN_13 =
    \\# Generated by //tools/build/readme_examples from R.md, the example at line 13. Do not edit: line n is README line n.
    \\
    \\
    \\
    \\
    \\
    \\
    \\
    \\
    \\
    \\
    \\
    \\
    \\from pkg import f
    \\
    \\
    \\@fieldwise_init
    \\struct P(Copyable):
    \\    var x: Int
    \\
    \\
    \\def main():
    \\    print(f(P(1).x))
    \\
    \\
    \\comptime S = """a
    \\  b"""
    \\
;

const RUNNER =
    \\# Generated by //tools/build/readme_examples from R.md. Do not edit: it runs each example's program, beside it.
    \\
    \\import readme_pkg_4
    \\import readme_pkg_13
    \\
    \\
    \\def main() raises:
    \\    var failed = 0
    \\    try:
    \\        readme_pkg_4.main()
    \\    except e:
    \\        failed += 1
    \\        print("R.md:4: FAILED: " + String(e))
    \\    try:
    \\        readme_pkg_13.main()
    \\    except e:
    \\        failed += 1
    \\        print("R.md:13: FAILED: " + String(e))
    \\    print("readme_pkg validation: " + String(2 - failed) + " of 2 checks passed")
    \\    if failed > 0:
    \\        raise Error(String(failed) + " of 2 README examples failed")
    \\
;

fn examplesOf(a: std.mem.Allocator, text: []const u8) ![]const ex.Example {
    return switch (try ex.extract(a, text, "R.md", false)) {
        .examples => |e| e,
        .refused => error.TestUnexpectedResult,
    };
}

fn programsOf(a: std.mem.Allocator, text: []const u8, package: []const u8) ![]const prog.Program {
    var why: []const u8 = "";
    return prog.generatePrograms(a, try examplesOf(a, text), package, "R.md", &why);
}

fn programOf(a: std.mem.Allocator, e: ex.Example) ![]const u8 {
    var why: []const u8 = "";
    return prog.exampleProgram(a, e, "R.md", &why);
}

/// Line `n` (1-based) of `text`.
fn lineOf(text: []const u8, n: usize) []const u8 {
    var it = std.mem.splitScalar(u8, text, '\n');
    var k: usize = 1;
    while (it.next()) |l| : (k += 1) {
        if (k == n) return l;
    }
    return "<past the end>";
}

test "golden" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const ps = try programsOf(arena.allocator(), README, "pkg");
    try t.expectEqual(@as(usize, 3), ps.len);
    try t.expectEqualStrings("readme_pkg_4.mojo", ps[0].name);
    try t.expectEqualStrings(GOLDEN_4, ps[0].text);
    try t.expectEqualStrings("readme_pkg_13.mojo", ps[1].name);
    try t.expectEqualStrings(GOLDEN_13, ps[1].text);
    try t.expectEqualStrings("readme_pkg.mojo", ps[2].name);
    try t.expectEqualStrings(RUNNER, ps[2].text);
}

test "every copied line is on its readme line" {
    // Line n of each program is README line n, with the indent its mode adds
    // (an indented fence's own indent removed first).
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const text = README ++ "\n- item\n\n  ```mojo\n  if True:\n      print(1)\n  ```\n";
    const exs = try examplesOf(a, text);
    try t.expectEqual(@as(usize, 3), exs.len);
    for (exs) |e| {
        const p = try programOf(a, e);
        for (e.code, e.code_lines) |c, n| {
            const want = if (e.module or c.len == 0) c else try std.mem.concat(a, u8, &.{ "    ", c });
            try t.expectEqualStrings(want, lineOf(p, n));
        }
    }
    // README line 34 is `      print(1)` (fence indent 2): line 34 of its
    // program is the line dedented by 2, then indented by 4.
    try t.expectEqualStrings("      print(1)", lineOf(text, 34));
    try t.expectEqualStrings("        print(1)", lineOf(try programOf(a, exs[2]), 34));
}

test "each example is its own program" {
    // Two examples importing the same name and declaring the same names:
    // each program holds its own import (nothing is deduplicated across
    // examples) and nothing of the other example.
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const ps = try programsOf(arena.allocator(), "```mojo\nfrom pkg import f\nvar x = f(1)\n```\n\n```mojo\nfrom pkg import f\nvar x = f(2)\n```\n", "q");
    try t.expectEqual(@as(usize, 3), ps.len);
    try t.expectEqualStrings("readme_q_1.mojo", ps[0].name);
    try t.expectEqualStrings("readme_q_6.mojo", ps[1].name);
    try t.expectEqualStrings("def main() raises:\n    from pkg import f\n    var x = f(1)\n", ps[0].text);
    try t.expectEqualStrings(
        "# Generated by //tools/build/readme_examples from R.md, the example at line 6. Do not edit: line n is README line n.\n" ++
            "\n\n\n\ndef main() raises:\n    from pkg import f\n    var x = f(2)\n",
        ps[1].text,
    );
}

test "the mode is the fence tag alone" {
    // A struct in a ```mojo example is pasted into main like any line (its
    // compile then fails); a ```mojo module example that declares nothing
    // but main gets no second main.
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const ps = try programsOf(arena.allocator(), "```mojo\nstruct T:\n    pass\nprint(1)\n```\n\n```mojo module\ndef main():\n    print(2)\n```\n", "pkg");
    try t.expectEqualStrings("def main() raises:\n    struct T:\n        pass\n    print(1)\n", ps[0].text);
    try t.expect(std.mem.endsWith(u8, ps[1].text, "\n\n\n\n\n\ndef main():\n    print(2)\n"));
    try t.expectEqual(@as(usize, 1), std.mem.count(u8, ps[1].text, "def main"));
}

test "a block with no code gets pass" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    try t.expectEqualStrings("def main() raises:\n    pass\n", (try programsOf(a, "```mojo\n```\n", "pkg"))[0].text);
    try t.expectEqualStrings("def main() raises:\n    # a comment\n\n    pass\n", (try programsOf(a, "```mojo\n# a comment\n\n```\n", "pkg"))[0].text);
    try t.expectEqualStrings("def main() raises:\n    print(1)  # not only a comment\n", (try programsOf(a, "```mojo\nprint(1)  # not only a comment\n```\n", "pkg"))[0].text);
}

test "a first line on readme line 1 is refused" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var why: []const u8 = "";
    const exs = try examplesOf(a, "<!-- mojo-hidden var x = 1 -->\n```mojo\nprint(x)\n```\n");
    try t.expectError(error.Refused, prog.generatePrograms(a, exs, "pkg", "R.md", &why));
    try t.expectEqualStrings("R.md:2: the example's first line is README line 1, which leaves no line for its `def main`", why);
    // A module example has no main to place: it may start on line 1.
    try t.expectEqualStrings("var x = 1\n", (try programsOf(a, "<!-- mojo-hidden var x = 1 -->\n```mojo module\n```\n", "pkg"))[0].text);
}

test "no example is a runner that runs nothing" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const ps = try programsOf(arena.allocator(), "# none\n", "q");
    try t.expectEqual(@as(usize, 1), ps.len);
    try t.expectEqualStrings("readme_q.mojo", ps[0].name);
    try t.expectEqualStrings(
        "# Generated by //tools/build/readme_examples from R.md. Do not edit: it runs each example's program, beside it.\n" ++
            "\n\ndef main():\n    print(\"NO EXAMPLE: R.md holds no ```mojo example\")\n",
        ps[0].text,
    );
}

test "the programs are never named like the package" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    try t.expectEqualStrings("readme_komira_x.mojo", try prog.programName(a, "komira_x"));
    try t.expectEqualStrings("readme_komira_x_12.mojo", try prog.exampleName(a, "komira_x", 12));
}

test "a mojo string literal escapes quote, backslash and newline" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    try t.expectEqualStrings("\"a\\\"b\\\\c\\nd\"", try prog.mojoStringLiteral(arena.allocator(), "a\"b\\c\nd"));
}

test "line map" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const report = "/w/out/readme_pkg_4.mojo:10:5: error: no f\n" ++
        "At readme_pkg_13.mojo:23:11: x\n" ++
        "at readme_pkg.mojo:9 (the runner)\n" ++
        "other_readme_pkg_4.mojo:3: untouched\n" ++
        "readme_pkg_4.main() and readme_pkg_4.mojo: too\n";
    try t.expectEqualStrings(
        "src/pkg/README.md:10:5: error: no f\n" ++
            "At src/pkg/README.md:23:11: x\n" ++
            "at readme_pkg.mojo:9 (the runner)\n" ++
            "other_readme_pkg_4.mojo:3: untouched\n" ++
            "readme_pkg_4.main() and readme_pkg_4.mojo: too\n",
        try prog.mapReport(arena.allocator(), report, "pkg", "src/pkg/README.md"),
    );
}
