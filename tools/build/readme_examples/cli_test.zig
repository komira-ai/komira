//! The commands as the build runs them: the files `generate` writes, what
//! each command prints, and its exit status (0, 1 refused, 2 usage or I/O).

const std = @import("std");
const cli = @import("cli.zig");
const t = std.testing;

const Arena = std.heap.ArenaAllocator;

/// A directory of its own under the test run's TMPDIR (the zig_test rule
/// gives each run one), removed by `done`.
const Scratch = struct {
    parent: std.fs.Dir,
    name: []const u8,
    dir: std.fs.Dir,

    fn init(a: std.mem.Allocator, name: []const u8) !Scratch {
        const tmp = std.process.getEnvVarOwned(a, "TMPDIR") catch try a.dupe(u8, "/tmp");
        var parent = try std.fs.cwd().openDir(tmp, .{});
        const sub = try std.fmt.allocPrint(a, "readme_examples_{s}_{d}", .{ name, std.os.linux.getpid() });
        try parent.makePath(sub);
        return .{ .parent = parent, .name = sub, .dir = try parent.openDir(sub, .{}) };
    }

    fn done(self: *Scratch) void {
        self.dir.close();
        self.parent.deleteTree(self.name) catch {};
        self.parent.close();
    }
};

const README = "# R\n\n```mojo\nprint(1)\n```\n\n```mojo module\ndef main():\n    pass\n```\n";

fn generateArgs(readme: []const u8, links: []const u8) [14][]const u8 {
    return .{ "tool", "generate", "--readme", readme, "--display", "src/r/README.md", "--package", "r", "--links", links, "--out-dir", "out/src", "--examples", "out/examples" };
}

test "generate writes one program per example, the runner and the example lines" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = try Scratch.init(a, "generate");
    defer tmp.done();
    try tmp.dir.writeFile("README.md", README);
    const args = generateArgs("README.md", "refuse");
    const o = cli.run(a, tmp.dir, &args);
    try t.expectEqualStrings("", o.stdout);
    try t.expectEqual(@as(u8, 0), o.code);
    try t.expectEqualStrings("3\n7\n", try tmp.dir.readFileAlloc(a, "out/examples", 1 << 20));
    try t.expectEqualStrings("# Generated by //tools/build/readme_examples from src/r/README.md, the example at line 3. Do not edit: line n is README line n.\n" ++
        "\ndef main() raises:\n    print(1)\n", try tmp.dir.readFileAlloc(a, "out/src/readme_r_3.mojo", 1 << 20));
    try t.expect(std.mem.endsWith(u8, try tmp.dir.readFileAlloc(a, "out/src/readme_r_7.mojo", 1 << 20), "\n\n\n\n\n\n\ndef main():\n    pass\n"));
    const runner = try tmp.dir.readFileAlloc(a, "out/src/readme_r.mojo", 1 << 20);
    try t.expect(std.mem.indexOf(u8, runner, "import readme_r_3\nimport readme_r_7\n") != null);
    // Nothing else: three programs.
    var d = try tmp.dir.openDir("out/src", .{ .iterate = true });
    defer d.close();
    var it = d.iterate();
    var n: usize = 0;
    while (try it.next()) |_| n += 1;
    try t.expectEqual(@as(usize, 3), n);
}

test "a refused README is exit 1, each reason naming its line, and writes nothing" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = try Scratch.init(a, "refused");
    defer tmp.done();
    try tmp.dir.writeFile("README.md", "See [x](x.md).\n\n```mojo skip\n```\n");
    const args = generateArgs("README.md", "refuse");
    const o = cli.run(a, tmp.dir, &args);
    try t.expectEqual(@as(u8, 1), o.code);
    try t.expectEqualStrings("src/r/README.md:1: x.md: a relative link in a README that ships in its package; the installed copy has no such file." ++
        " Link an absolute URL, or an #anchor of this README\n" ++
        "src/r/README.md:3: `mojo skip`: an example's info string is `mojo` or `mojo module`; nothing else may follow `mojo`" ++
        " (there is no skip word: fence a sketch that cannot run as ```text)\n", o.stdout);
    try t.expectError(error.FileNotFound, tmp.dir.access("out/examples", .{}));
    // --links allow: the link passes, the fence word does not.
    const allow = generateArgs("README.md", "allow");
    const o2 = cli.run(a, tmp.dir, &allow);
    try t.expectEqual(@as(u8, 1), o2.code);
    try t.expect(std.mem.startsWith(u8, o2.stdout, "src/r/README.md:3: `mojo skip`"));
}

test "no example: an empty examples file and a runner that runs nothing" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = try Scratch.init(a, "none");
    defer tmp.done();
    try tmp.dir.writeFile("README.md", "# none\n");
    const args = generateArgs("README.md", "allow");
    try t.expectEqual(@as(u8, 0), cli.run(a, tmp.dir, &args).code);
    try t.expectEqualStrings("", try tmp.dir.readFileAlloc(a, "out/examples", 1 << 20));
    try t.expect(std.mem.indexOf(u8, try tmp.dir.readFileAlloc(a, "out/src/readme_r.mojo", 1 << 20), "NO EXAMPLE: src/r/README.md") != null);
}

test "usage: every flag required, none unknown or twice, a value for each; exit 2" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = try Scratch.init(a, "usage");
    defer tmp.done();
    const cases = [_]struct { argv: []const []const u8, first: []const u8 }{
        .{ .argv = &.{"tool"}, .first = "readme-examples: no subcommand\n" },
        .{ .argv = &.{ "tool", "gen" }, .first = "readme-examples: unknown subcommand gen\n" },
        .{ .argv = &.{ "tool", "map", "--package", "p", "--display", "d" }, .first = "readme-examples: --report is required\n" },
        .{ .argv = &.{ "tool", "map", "--package", "p", "--display", "d", "--report=" }, .first = "readme-examples: --report is required\n" },
        .{ .argv = &.{ "tool", "map", "--package", "p", "--package", "q" }, .first = "readme-examples: --package given twice\n" },
        .{ .argv = &.{ "tool", "map", "--pkg", "p" }, .first = "readme-examples: unknown flag --pkg\n" },
        .{ .argv = &.{ "tool", "map", "--package" }, .first = "readme-examples: --package needs a value\n" },
        .{ .argv = &.{ "tool", "generate", "--readme", "R", "--display", "d", "--package", "p", "--links", "maybe", "--out-dir", "o", "--examples", "e" }, .first = "readme-examples: --links is allow or refuse, not maybe\n" },
    };
    for (cases) |c| {
        const o = cli.run(a, tmp.dir, c.argv);
        try t.expectEqual(@as(u8, 2), o.code);
        try t.expect(std.mem.startsWith(u8, o.stdout, c.first));
        try t.expect(std.mem.endsWith(u8, o.stdout, "       tool map --package NAME --display NAME --report F\n"));
    }
    // A README it cannot read.
    const args = generateArgs("missing.md", "allow");
    const o = cli.run(a, tmp.dir, &args);
    try t.expectEqual(@as(u8, 2), o.code);
    try t.expect(std.mem.startsWith(u8, o.stdout, "readme-examples: cannot read missing.md: "));
}

test "map prints the report with each example's line mapped to the README" {
    var arena = Arena.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = try Scratch.init(a, "map");
    defer tmp.done();
    try tmp.dir.writeFile("report", "x/readme_p_7.mojo:9:3: error: e\nreadme_p.mojo:4\n");
    const o = cli.run(a, tmp.dir, &.{ "tool", "map", "--package=p", "--display", "src/p/README.md", "--report", "report" });
    try t.expectEqual(@as(u8, 0), o.code);
    try t.expectEqualStrings("src/p/README.md:9:3: error: e\nreadme_p.mojo:4\n", o.stdout);
}
