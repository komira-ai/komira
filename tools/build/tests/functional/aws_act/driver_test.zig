//! The process behaviour of `aws_act gen` (tools/build/cloud/aws_act.zig) over a
//! stand-in generator (fake_gen.zig).
const std = @import("std");
const kit = @import("driver_kit");
const t = std.testing;
const has = kit.has;

fn newCtx(name: []const u8) !kit.Ctx {
    return kit.Ctx.init(name, "AWS_ACT");
}

fn genArgs(c: *kit.Ctx, mode: []const u8, hands: []const []const u8) ![]const []const u8 {
    var list = std.ArrayList([]const u8).empty;
    try list.appendSlice(c.alloc(), &.{ "gen", "--gen", try c.env("FAKE_GEN"), "--out", "pkg", "--module", "svc", "--hands" });
    try list.append(c.alloc(), try std.fmt.allocPrint(c.alloc(), "{d}", .{hands.len}));
    for (hands) |h| try list.appendSlice(c.alloc(), &.{ "--hand", h });
    try list.appendSlice(c.alloc(), &.{ "--", "--model", "m.json", "--operations", "A,B", mode });
    return list.items;
}

test "gen: the generator gets --module, --out and --probe-out then its arguments; the package is the module, the probe, __init__ and the hand-written sources" {
    var c = try newCtx("gen_ok");
    defer c.deinit();
    try c.write("src/hand_a.mojo", "# hand a\n", 0o644);
    try c.write("src/hand_b.mojo", "# hand b\n", 0o644);
    const r = try c.run(try genArgs(&c, "mode=ok", &.{ "src/hand_a.mojo", "src/hand_b.mojo" }), &.{});
    if (r.code != 0) std.debug.print("[aws_act stderr] {s}\n", .{r.stderr});
    try t.expectEqual(@as(u8, 0), r.code);
    try t.expectEqualStrings("module=svc\nrest:--model\nrest:m.json\nrest:--operations\nrest:A,B\nrest:mode=ok\n", r.stdout);
    try t.expectEqualStrings("# generated module\n", try c.read("pkg/svc.mojo"));
    try t.expectEqualStrings("# probe\n", try c.read("pkg/_layout_probe.mojo"));
    try t.expectEqualStrings("# @generated by mojo_aws_client (tools/build/cloud/aws.bzl) version 1\n# DO NOT EDIT. Generated by mojo_aws_client; the module beside it pins its model.\n", try c.read("pkg/__init__.mojo"));
    try t.expectEqualStrings("# hand a\n", try c.read("pkg/hand_a.mojo"));
    try t.expectEqualStrings("# hand b\n", try c.read("pkg/hand_b.mojo"));
    // The parts directory is in every package, with a header of its own and nothing else.
    try t.expectEqualStrings("# @generated by mojo_aws_client (tools/build/cloud/aws.bzl) version 1\n# DO NOT EDIT. Generated by mojo_aws_client; the parts of the module beside it, when it is too large for one file.\n", try c.read("pkg/_parts/__init__.mojo"));
    try t.expect(!c.exists("pkg/_parts/svc_p01.mojo"));
    // no hand-written sources is a package of three files and the parts directory
    const r2 = try c.run(&.{ "gen", "--gen", try c.env("FAKE_GEN"), "--out", "pkg2", "--module", "svc", "--hands", "0", "--", "mode=ok" }, &.{});
    try t.expectEqual(@as(u8, 0), r2.code);
    try t.expect(c.exists("pkg2/__init__.mojo"));
    try t.expect(c.exists("pkg2/_parts/__init__.mojo"));
    try t.expect(!c.exists("pkg2/hand_a.mojo"));
}

test "gen: the parts of a split module are kept beside the parts directory's own __init__; a stray or empty file among them is refused" {
    var c = try newCtx("gen_parts");
    defer c.deinit();
    const ok = try c.run(try genArgs(&c, "mode=parts", &.{}), &.{});
    if (ok.code != 0) std.debug.print("[aws_act stderr] {s}\n", .{ok.stderr});
    try t.expectEqual(@as(u8, 0), ok.code);
    try t.expectEqualStrings("# a part\n", try c.read("pkg/_parts/svc_p01.mojo"));
    try t.expectEqualStrings("# a part\n", try c.read("pkg/_parts/svc_p02.mojo"));
    try t.expect(c.exists("pkg/_parts/__init__.mojo"));
    const stray = try c.run(try genArgs(&c, "mode=parts_stray", &.{}), &.{});
    try t.expectEqual(@as(u8, 1), stray.code);
    try t.expect(has(stray.stderr, "_parts/notes.txt is not a .mojo file"));
    try std.fs.cwd().deleteFile(try c.path("pkg/_parts/notes.txt"));
    const empty = try c.run(try genArgs(&c, "mode=parts_empty", &.{}), &.{});
    try t.expectEqual(@as(u8, 1), empty.code);
    try t.expect(has(empty.stderr, "_parts/svc_p02.mojo is empty"));
}

test "gen: the generator's own failure, an empty or missing module, a stray file, and a hand-written file the package already holds are each refused" {
    var c = try newCtx("gen_bad");
    defer c.deinit();
    try c.write("src/hand_a.mojo", "# hand a\n", 0o644);
    const r1 = try c.run(try genArgs(&c, "mode=exit3", &.{}), &.{});
    try t.expectEqual(@as(u8, 3), r1.code);
    const r2 = try c.run(try genArgs(&c, "mode=empty", &.{}), &.{});
    try t.expectEqual(@as(u8, 1), r2.code);
    try t.expectEqualStrings("aws-client-gen wrote no code (or an empty file) for the expected svc.mojo\n", r2.stderr);
    const r3 = try c.run(try genArgs(&c, "mode=none", &.{}), &.{});
    try t.expectEqual(@as(u8, 1), r3.code);
    try t.expect(has(r3.stderr, "for the expected svc.mojo"));
    const r4 = try c.run(try genArgs(&c, "mode=extra", &.{}), &.{});
    try t.expectEqual(@as(u8, 1), r4.code);
    try t.expect(has(r4.stderr, "mojo_aws_client: the generated package holds files that were not declared:\n"));
    try t.expect(has(r4.stderr, "stray.mojo\n"));
    // a hand-written source named like a generated file merges into it: one file fewer
    try std.fs.cwd().deleteFile(try c.path("pkg/stray.mojo"));
    try c.write("src/svc.mojo", "# hand\n", 0o644);
    const r5 = try c.run(try genArgs(&c, "mode=ok", &.{"src/svc.mojo"}), &.{});
    try t.expectEqual(@as(u8, 1), r5.code);
    // usage
    try t.expectEqual(@as(u8, 2), (try c.run(&.{ "gen", "--gen", "x" }, &.{})).code);
    try t.expectEqual(@as(u8, 2), (try c.run(&.{ "gen", "--gen", "g", "--out", "o", "--module", "m", "--hands", "2", "--hand", "a", "--" }, &.{})).code);
    try t.expectEqual(@as(u8, 2), (try c.run(&.{}, &.{})).code);
    try t.expectEqual(@as(u8, 2), (try c.run(&.{"frobnicate"}, &.{})).code);
}
