// Why Zig: build tools are Zig (tools/build/README.md). aws_act replaces the
// busybox script of `mojo_aws_client`'s generation action (aws.bzl), so that
// action runs no shell.
//! aws_act: the action of the `mojo_aws_client` generation rule.
//!
//!   aws_act gen --gen <generator> --out <dir> --module <name> --hands <n>
//!       [--hand <file>]... -- <generator arguments>...
//!
//! Runs <generator> with `--module <name> --out <dir>/<name>.mojo --probe-out
//! <dir>/_layout_probe.mojo` and the arguments after `--`, writes
//! <dir>/__init__.mojo, copies each hand-written source into <dir>, and holds
//! the directory to exactly the expected files, none of the two generated ones
//! empty: an empty module is a silent generator failure, and an unexpected file
//! would not be compiled.
//!
//! The messages and exit statuses are those of the script it replaces.

const std = @import("std");
const U = @import("act_util");

const prog = "aws_act";

fn usage(comptime fmt: []const u8, args: anytype) u8 {
    std.debug.print(prog ++ ": " ++ fmt ++ "\n", args);
    return 2;
}

/// The two lines of the package's `__init__.mojo`: the generated-file header
/// of `komira_proto_codegen::header` (the first line carries `@generated`, the
/// last says not to edit it and names the regenerate command), with no input
/// pin of its own: the module beside it pins its model. The command is the one
/// of `tools/build/proto-codegen/src/header.rs`;
/// `tools/build/gen:command_agreement` holds the two equal.
pub const init_text =
    "# @generated by mojo_aws_client (tools/build/cloud/aws.bzl) version 1\n" ++
    "# DO NOT EDIT. Regenerate with `./buck2 run komira//tools/build/gen:regen -- <library target>`. Generated by mojo_aws_client; the module beside it pins its model.\n";

pub const probe_name = "_layout_probe.mojo";

/// The entries `dir` holds after the generation, against the files expected:
/// null when it is exactly them (and the generated ones are not empty), else
/// the reason, in the script's words.
pub fn judge(a: std.mem.Allocator, dir: std.fs.Dir, module: []const u8, hands: usize) !?[]u8 {
    const files = [_][]const u8{ try std.fmt.allocPrint(a, "{s}.mojo", .{module}), probe_name };
    for (files) |f| {
        const st = dir.statFile(f) catch null;
        if (st == null or st.?.size == 0) {
            return try std.fmt.allocPrint(a, "aws-client-gen wrote no code (or an empty file) for the expected {s}\n", .{f});
        }
    }
    const names = try U.listNames(a, dir);
    if (names.len != 3 + hands) {
        var b = std.ArrayList(u8).empty;
        try b.appendSlice(a, "mojo_aws_client: the generated package holds files that were not declared:\n");
        for (names) |n| {
            try b.appendSlice(a, n);
            try b.append(a, '\n');
        }
        return b.items;
    }
    return null;
}

fn cmdGen(a: std.mem.Allocator, args: []const []const u8) u8 {
    const spec = [_]U.Spec{ .{ .name = "gen" }, .{ .name = "out" }, .{ .name = "module" }, .{ .name = "hands" }, .{ .name = "hand" } };
    var bad: []const u8 = "";
    const f = U.parseFlags(a, args, &spec, &bad) catch |e| return usage("gen: {s}: {s}", .{ @errorName(e), bad });
    const gen = f.need("gen") catch return usage("gen needs --gen", .{});
    const out = f.need("out") catch return usage("gen needs --out", .{});
    const module = f.need("module") catch return usage("gen needs --module", .{});
    const n_text = f.need("hands") catch return usage("gen needs --hands", .{});
    const n = std.fmt.parseInt(usize, n_text, 10) catch return usage("--hands is a count, not {s}", .{n_text});
    const hands = f.all(a, "hand") catch return 2;
    if (hands.len != n) return usage("--hands says {d}, but {d} --hand were given", .{ n, hands.len });

    std.fs.cwd().makePath(out) catch |e| return usage("cannot create {s}: {s}", .{ out, @errorName(e) });
    const cwd = std.fs.cwd().realpathAlloc(a, ".") catch return 2;
    const gen_abs = U.abs(a, cwd, gen) catch return 2;
    var argv = std.ArrayList([]const u8).empty;
    argv.append(a, gen_abs) catch return 2;
    argv.append(a, "--module") catch return 2;
    argv.append(a, module) catch return 2;
    argv.append(a, "--out") catch return 2;
    argv.append(a, std.fmt.allocPrint(a, "{s}/{s}.mojo", .{ out, module }) catch return 2) catch return 2;
    argv.append(a, "--probe-out") catch return 2;
    argv.append(a, std.fmt.allocPrint(a, "{s}/{s}", .{ out, probe_name }) catch return 2) catch return 2;
    argv.appendSlice(a, f.rest) catch return 2;
    var child = std.process.Child.init(argv.items, a);
    const term = child.spawnAndWait() catch |e| return usage("cannot run {s}: {s}", .{ gen, @errorName(e) });
    const code = U.exitCodeOf(term);
    if (code != 0) return code;

    var dir = std.fs.cwd().openDir(out, .{ .iterate = true }) catch |e| return usage("cannot open {s}: {s}", .{ out, @errorName(e) });
    defer dir.close();
    U.writeAll(dir, "__init__.mojo", init_text) catch |e| return usage("cannot write {s}/__init__.mojo: {s}", .{ out, @errorName(e) });
    for (hands) |h| {
        const src = h.vals[0];
        std.fs.cwd().copyFile(src, dir, std.fs.path.basename(src), .{}) catch |e| return usage("cannot copy {s} to {s}: {s}", .{ src, out, @errorName(e) });
    }
    const why = judge(a, dir, module, n) catch return 2;
    if (why) |text| {
        std.debug.print("{s}", .{text});
        return 1;
    }
    return 0;
}

pub fn main() void {
    var arena_state = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    const a = arena_state.allocator();
    const argv = std.process.argsAlloc(a) catch std.process.exit(2);
    if (argv.len < 2) std.process.exit(usage("usage: aws_act gen ...", .{}));
    const plain = a.alloc([]const u8, argv.len - 2) catch std.process.exit(2);
    for (argv[2..], 0..) |s, i| plain[i] = s;
    const rc: u8 = if (std.mem.eql(u8, argv[1], "gen")) cmdGen(a, plain) else usage("unknown subcommand {s}", .{argv[1]});
    if (rc != 0) std.process.exit(rc);
}
