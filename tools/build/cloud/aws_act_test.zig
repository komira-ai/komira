//! Unit tests of aws_act's check of the generated package. Its process
//! behaviour (the generator run, the files written, the refusals) is
//! tests//functional/aws_act; every mojo_aws_client of the repository runs
//! through it too.
const std = @import("std");
const A = @import("aws_act.zig");
const U = @import("act_util");
const t = std.testing;

fn lay(dir: std.fs.Dir, names: []const []const u8) !void {
    for (names) |n| try U.writeAll(dir, n, "x");
}

/// What `cmdGen` leaves: the parts directory with its own `__init__.mojo`.
fn layParts(dir: std.fs.Dir) !void {
    try dir.makePath("_parts");
    try U.writeAll(dir, "_parts/__init__.mojo", A.parts_init_text);
}

test "judge: exactly the module, the probe, __init__ and the hand-written sources" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try lay(tmp.dir, &.{ "svc.mojo", "_layout_probe.mojo", "__init__.mojo" });
    try layParts(tmp.dir);
    try t.expect((try A.judge(a, tmp.dir, "svc", 0)) == null);
    // a hand-written source is expected only when it is declared
    try lay(tmp.dir, &.{"hand.mojo"});
    try t.expectEqualStrings("mojo_aws_client: the generated package holds files that were not declared:\n__init__.mojo\n_layout_probe.mojo\n_parts\nhand.mojo\nsvc.mojo\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
    try t.expect((try A.judge(a, tmp.dir, "svc", 1)) == null);
    // a declared source that was not copied
    try t.expect((try A.judge(a, tmp.dir, "svc", 2)) != null);
}

test "judge: a missing or empty generated file is a silent generator failure" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try lay(tmp.dir, &.{ "_layout_probe.mojo", "__init__.mojo" });
    try layParts(tmp.dir);
    try t.expectEqualStrings("aws-client-gen wrote no code (or an empty file) for the expected svc.mojo\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
    try U.writeAll(tmp.dir, "svc.mojo", "");
    try t.expectEqualStrings("aws-client-gen wrote no code (or an empty file) for the expected svc.mojo\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
    try U.writeAll(tmp.dir, "svc.mojo", "x");
    try U.writeAll(tmp.dir, "_layout_probe.mojo", "");
    try t.expectEqualStrings("aws-client-gen wrote no code (or an empty file) for the expected _layout_probe.mojo\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
}

test "judge: the parts of a split module are accepted; a stray or empty file among them is refused" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try lay(tmp.dir, &.{ "svc.mojo", "_layout_probe.mojo", "__init__.mojo" });
    try tmp.dir.makeDir("_parts");
    try U.writeAll(tmp.dir, "_parts/__init__.mojo", "");
    try t.expectEqualStrings("mojo_aws_client: the generated parts directory holds a file that would not be compiled: _parts/__init__.mojo is empty\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
    try U.writeAll(tmp.dir, "_parts/__init__.mojo", A.parts_init_text);
    try lay(tmp.dir, &.{ "_parts/svc_p01.mojo", "_parts/svc_p02.mojo" });
    try t.expect((try A.judge(a, tmp.dir, "svc", 0)) == null);
    try U.writeAll(tmp.dir, "_parts/svc_p03.mojo", "");
    try t.expectEqualStrings("mojo_aws_client: the generated parts directory holds a file that would not be compiled: _parts/svc_p03.mojo is empty\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
    try U.writeAll(tmp.dir, "_parts/svc_p03.mojo", "x");
    try U.writeAll(tmp.dir, "_parts/readme.txt", "x");
    try t.expectEqualStrings("mojo_aws_client: the generated parts directory holds a file that would not be compiled: _parts/readme.txt is not a .mojo file\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
}

test "judge: a package whose parts entry is a file, not a directory, is refused" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try lay(tmp.dir, &.{ "svc.mojo", "_layout_probe.mojo", "__init__.mojo", "_parts" });
    try t.expectEqualStrings("mojo_aws_client: the generated package has no _parts directory\n", (try A.judge(a, tmp.dir, "svc", 0)).?);
}

test "parts_init_text is a generated-file header" {
    try t.expectEqualStrings("# @generated by mojo_aws_client (tools/build/cloud/aws.bzl) version 1\n# DO NOT EDIT. Generated by mojo_aws_client; the parts of the module beside it, when it is too large for one file.\n", A.parts_init_text);
    var lines = std.mem.splitScalar(u8, A.parts_init_text, '\n');
    try t.expect(std.mem.startsWith(u8, lines.first(), "# @generated "));
}

test "init_text is the two comment lines the script wrote" {
    try t.expectEqualStrings("# @generated by mojo_aws_client (tools/build/cloud/aws.bzl) version 1\n# DO NOT EDIT. Regenerate with `./buck2 run komira//tools/build/gen:regen -- <library target>`. Generated by mojo_aws_client; the module beside it pins its model.\n", A.init_text);
    var lines = std.mem.splitScalar(u8, A.init_text, '\n');
    try t.expect(std.mem.startsWith(u8, lines.first(), "# @generated "));
}
