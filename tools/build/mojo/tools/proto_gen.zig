// Why Zig: build tools are Zig (tools/build/README.md). This replaces the
// busybox shell script of the proto rules' generation action, so that running
// protoc with a plugin runs no shell.
//! proto_gen: runs protoc with a code-generation plugin into one directory and
//! holds the result to the files the rule declared.
//!
//! usage: proto_gen <busybox> <protoc dir> <plugin> <plugin name> <out dir> <plugin options>
//!            <N> <proto path>... <M> <expected file>... <proto file>...
//!
//! It runs `<protoc dir>/bin/protoc --proto_path=<each path> --proto_path=<protoc
//! dir>/include --plugin=protoc-gen-<name>=<plugin> --<name>_out=<out dir>
//! --<name>_opt=<options> <proto file>...` with the busybox applets as PATH and a
//! TMPDIR and HOME of its own, then writes `<out dir>/__init__.mojo` and refuses
//! the result unless the directory holds exactly the M expected files (none
//! empty) and that one. protoc looks the plugin up as protoc-gen-<name> and hands
//! it the descriptors of the whole import closure, so no descriptor set is passed.
//!
//! Exit status: protoc's when it fails; 1 for an expected file that is missing
//! or empty, or a file that was not declared; 2 for a usage error or a failure
//! of the tool's own.

const std = @import("std");

/// The package's `__init__.mojo`: the generated-file header of
/// `komira_proto_codegen::header` (the first line carries `@generated`, the
/// last says not to edit it and names the regenerate command), with no input
/// pin of its own: the modules beside it pin theirs. The command is the one of
/// `tools/build/proto-codegen/src/header.rs`; `tools/build/gen:command_agreement`
/// holds the two equal.
pub const init_text =
    "# @generated by the Mojo proto rules (tools/build/mojo/proto.bzl) version 1\n" ++
    "# DO NOT EDIT. Regenerate with `./buck2 run komira//tools/build/gen:regen -- <library target>`. Generated by the Mojo proto rules; the modules beside it pin their inputs.\n";

pub const Check = union(enum) {
    ok,
    /// The expected file that is missing or empty.
    empty: []const u8,
    /// The entries of the directory when it holds files that were not declared.
    undeclared: []const []const u8,
};

/// Whether `dir` holds exactly `expected` (each non-empty) and `__init__.mojo`.
pub fn checkOutputs(a: std.mem.Allocator, dir: std.fs.Dir, expected: []const []const u8) !Check {
    for (expected) |f| {
        const st = dir.statFile(f) catch return .{ .empty = f };
        if (st.size == 0) return .{ .empty = f };
    }
    var names = std.ArrayList([]const u8).empty;
    var it = dir.iterate();
    while (try it.next()) |e| try names.append(a, try a.dupe(u8, e.name));
    if (names.items.len != expected.len + 1) {
        std.mem.sort([]const u8, names.items, {}, struct {
            fn lt(_: void, x: []const u8, y: []const u8) bool {
                return std.mem.lessThan(u8, x, y);
            }
        }.lt);
        return .{ .undeclared = try names.toOwnedSlice(a) };
    }
    return .ok;
}

fn die(code: u8, comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("proto_gen: " ++ fmt ++ "\n", args);
    std.process.exit(code);
}

pub fn exitCodeOf(term: std.process.Child.Term) u8 {
    return switch (term) {
        .Exited => |c| c,
        .Signal => |s| @truncate(128 +% s),
        else => 1,
    };
}

pub fn main() !void {
    var arena_state = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    const a = arena_state.allocator();
    const argv = try std.process.argsAlloc(a);
    if (argv.len < 9) die(2, "usage: proto_gen <busybox> <protoc dir> <plugin> <name> <out> <options> <N> <path>... <M> <expected>... <proto>...", .{});
    const cwd = try std.fs.cwd().realpathAlloc(a, ".");
    const abs = struct {
        fn of(al: std.mem.Allocator, base: []const u8, p: []const u8) ![]u8 {
            return if (std.fs.path.isAbsolute(p)) al.dupe(u8, p) else std.fs.path.join(al, &.{ base, p });
        }
    }.of;
    const busybox = try abs(a, cwd, argv[1]);
    const protoc_dir = argv[2];
    const plugin = try abs(a, cwd, argv[3]);
    const name = argv[4];
    const out_dir = argv[5];
    const opt = argv[6];
    var i: usize = 7;
    const n_paths = std.fmt.parseInt(usize, argv[i], 10) catch die(2, "the number of proto paths is not a number: {s}", .{argv[i]});
    i += 1;
    if (i + n_paths >= argv.len) die(2, "too few arguments", .{});
    const paths = argv[i .. i + n_paths];
    i += n_paths;
    const n_exp = std.fmt.parseInt(usize, argv[i], 10) catch die(2, "the number of expected files is not a number: {s}", .{argv[i]});
    i += 1;
    if (i + n_exp > argv.len) die(2, "too few arguments", .{});
    const expected = argv[i .. i + n_exp];
    const protos = argv[i + n_exp ..];

    const env_scratch = std.process.getEnvVarOwned(a, "BUCK_SCRATCH_PATH") catch "";
    const t = if (env_scratch.len == 0)
        try std.fs.path.join(a, &.{ cwd, ".komira_action" })
    else if (std.fs.path.isAbsolute(env_scratch))
        try std.fs.path.join(a, &.{ env_scratch, "komira" })
    else
        try std.fs.path.join(a, &.{ cwd, env_scratch, "komira" });
    const bin = try std.fs.path.join(a, &.{ t, "bin" });
    const tmp = try std.fs.path.join(a, &.{ t, "tmp" });
    try std.fs.cwd().makePath(bin);
    try std.fs.cwd().makePath(tmp);
    try std.fs.cwd().makePath(out_dir);

    var env = try std.process.getEnvMap(a);
    var install = std.process.Child.init(&.{ busybox, "--install", "-s", bin }, a);
    install.env_map = &env;
    const installed = install.spawnAndWait() catch |e| die(2, "cannot run {s}: {s}", .{ busybox, @errorName(e) });
    if (exitCodeOf(installed) != 0) die(2, "{s} --install -s {s} failed", .{ busybox, bin });
    try env.put("PATH", bin);
    try env.put("TMPDIR", tmp);
    try env.put("HOME", t);

    var args = std.ArrayList([]const u8).empty;
    try args.append(a, try std.fs.path.join(a, &.{ protoc_dir, "bin", "protoc" }));
    for (paths) |p| try args.append(a, try std.fmt.allocPrint(a, "--proto_path={s}", .{p}));
    try args.append(a, try std.fmt.allocPrint(a, "--proto_path={s}/include", .{protoc_dir}));
    try args.append(a, try std.fmt.allocPrint(a, "--plugin=protoc-gen-{s}={s}", .{ name, plugin }));
    try args.append(a, try std.fmt.allocPrint(a, "--{s}_out={s}", .{ name, out_dir }));
    try args.append(a, try std.fmt.allocPrint(a, "--{s}_opt={s}", .{ name, opt }));
    try args.appendSlice(a, protos);
    var child = std.process.Child.init(args.items, a);
    child.env_map = &env;
    const term = child.spawnAndWait() catch |e| die(2, "cannot run {s}: {s}", .{ args.items[0], @errorName(e) });
    const rc = exitCodeOf(term);
    if (rc != 0) std.process.exit(rc);

    const init_path = try std.fs.path.join(a, &.{ out_dir, "__init__.mojo" });
    {
        const f = std.fs.cwd().createFile(init_path, .{}) catch |e| die(2, "cannot create {s}: {s}", .{ init_path, @errorName(e) });
        defer f.close();
        try f.writeAll(init_text);
    }
    var dir = try std.fs.cwd().openDir(out_dir, .{ .iterate = true });
    defer dir.close();
    switch (try checkOutputs(a, dir, expected)) {
        .ok => {},
        .empty => |f| {
            std.debug.print("protoc-gen-{s} wrote no code (or an empty file) for the expected {s}\n", .{ name, f });
            std.process.exit(1);
        },
        .undeclared => |names| {
            std.debug.print("protoc-gen-{s} wrote files that were not declared:\n", .{name});
            for (names) |n| std.debug.print("{s}\n", .{n});
            std.process.exit(1);
        },
    }
    std.fs.cwd().deleteTree(t) catch {};
}
