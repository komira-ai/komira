//! Unit tests of proto_gen.zig's output check. The whole tool (protoc, the
//! plugin, the environment) is run by every proto library of the repository
//! and by tests//negative/proto.
const std = @import("std");
const P = @import("proto_gen.zig");
const t = std.testing;

fn put(dir: std.fs.Dir, name: []const u8, data: []const u8) !void {
    const f = try dir.createFile(name, .{});
    defer f.close();
    try f.writeAll(data);
}

/// What `main` leaves beside the expected files: the parts directory and its `__init__.mojo`.
fn layParts(dir: std.fs.Dir) !void {
    try dir.makePath("_parts");
    try put(dir, "_parts/__init__.mojo", P.parts_init_text);
}

test "parts_init_text: a generated-file header of two comment lines" {
    var lines = std.mem.splitScalar(u8, P.parts_init_text, '\n');
    try t.expect(std.mem.startsWith(u8, lines.first(), "# @generated "));
    try t.expect(std.mem.startsWith(u8, lines.next().?, "# DO NOT EDIT. Generated by"));
}

test "init_text: a generated-file header of two comment lines" {
    try t.expectEqualStrings(
        "# @generated by the Mojo proto rules (tools/build/mojo/proto.bzl) version 1\n" ++
            "# DO NOT EDIT. Generated by the Mojo proto rules; the modules beside it pin their inputs.\n",
        P.init_text,
    );
    var lines = std.mem.splitScalar(u8, P.init_text, '\n');
    try t.expect(std.mem.startsWith(u8, lines.first(), "# @generated "));
}

test "checkOutputs: exactly the expected files and __init__.mojo is ok" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try put(tmp.dir, "__init__.mojo", P.init_text);
    try put(tmp.dir, "a_pb.mojo", "x");
    try put(tmp.dir, "b_pb.mojo", "y");
    try layParts(tmp.dir);
    const c = try P.checkOutputs(arena.allocator(), tmp.dir, &.{ "a_pb.mojo", "b_pb.mojo" });
    try t.expect(c == .ok);
    // No expected files: only __init__.mojo and the parts directory.
    var only = t.tmpDir(.{ .iterate = true });
    defer only.cleanup();
    try put(only.dir, "__init__.mojo", P.init_text);
    try layParts(only.dir);
    try t.expect((try P.checkOutputs(arena.allocator(), only.dir, &.{})) == .ok);
}

test "checkOutputs: a missing or an empty expected file is named" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try put(tmp.dir, "__init__.mojo", P.init_text);
    try layParts(tmp.dir);
    try put(tmp.dir, "a_pb.mojo", "x");
    try put(tmp.dir, "empty_pb.mojo", "");
    const missing = try P.checkOutputs(arena.allocator(), tmp.dir, &.{ "a_pb.mojo", "gone_pb.mojo" });
    try t.expectEqualStrings("gone_pb.mojo", missing.empty);
    const empty = try P.checkOutputs(arena.allocator(), tmp.dir, &.{ "empty_pb.mojo", "a_pb.mojo" });
    try t.expectEqualStrings("empty_pb.mojo", empty.empty);
}

test "checkOutputs: an undeclared file (or directory) is refused, with the sorted listing" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try put(tmp.dir, "__init__.mojo", P.init_text);
    try put(tmp.dir, "a_pb.mojo", "x");
    try put(tmp.dir, "z_extra.mojo", "y");
    try tmp.dir.makeDir("sub");
    try layParts(tmp.dir);
    const c = try P.checkOutputs(arena.allocator(), tmp.dir, &.{"a_pb.mojo"});
    try t.expectEqual(@as(usize, 5), c.undeclared.len);
    try t.expectEqualStrings("__init__.mojo", c.undeclared[0]);
    try t.expectEqualStrings("_parts", c.undeclared[1]);
    try t.expectEqualStrings("a_pb.mojo", c.undeclared[2]);
    try t.expectEqualStrings("sub", c.undeclared[3]);
    try t.expectEqualStrings("z_extra.mojo", c.undeclared[4]);
}

test "checkOutputs: the parts of a split module are accepted; a stray or empty file among them is refused" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try put(tmp.dir, "__init__.mojo", P.init_text);
    try put(tmp.dir, "a_pb.mojo", "x");
    try layParts(tmp.dir);
    try put(tmp.dir, "_parts/a_pb_p01.mojo", "x");
    try put(tmp.dir, "_parts/a_pb_p02.mojo", "x");
    try t.expect((try P.checkOutputs(arena.allocator(), tmp.dir, &.{"a_pb.mojo"})) == .ok);
    try put(tmp.dir, "_parts/a_pb_p03.mojo", "");
    const empty = try P.checkOutputs(arena.allocator(), tmp.dir, &.{"a_pb.mojo"});
    try t.expectEqualStrings("_parts/a_pb_p03.mojo is empty", empty.parts);
    try put(tmp.dir, "_parts/a_pb_p03.mojo", "x");
    try put(tmp.dir, "_parts/notes.txt", "x");
    const stray = try P.checkOutputs(arena.allocator(), tmp.dir, &.{"a_pb.mojo"});
    try t.expectEqualStrings("_parts/notes.txt is not a .mojo file", stray.parts);
}

test "checkOutputs: a package with no parts directory is refused" {
    var arena = std.heap.ArenaAllocator.init(t.allocator);
    defer arena.deinit();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try put(tmp.dir, "__init__.mojo", P.init_text);
    try put(tmp.dir, "a_pb.mojo", "x");
    // A file named like the directory makes the count right and the entry wrong.
    try put(tmp.dir, "_parts", "x");
    const c = try P.checkOutputs(arena.allocator(), tmp.dir, &.{"a_pb.mojo"});
    try t.expectEqualStrings("_parts is missing or is not a directory", c.parts);
}

test "exitCodeOf: a child's status, 128 + N for a signal" {
    try t.expectEqual(@as(u8, 1), P.exitCodeOf(.{ .Exited = 1 }));
    try t.expectEqual(@as(u8, 139), P.exitCodeOf(.{ .Signal = 11 }));
}
