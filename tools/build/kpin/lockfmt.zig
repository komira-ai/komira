//! pins.lock.bzl: the lock model, its one rendering, and a reader for that
//! rendering (a small, strict parser for the Starlark literals kpin writes).
//!
//! Rendering is canonical: entries are sorted by name (and by platform), a
//! value is a string or an integer, and every string passed `valid.zig`. The
//! same lock always renders to the same bytes, which is what lets `check`
//! compare bytes.

const std = @import("std");
const valid = @import("valid.zig");
const Diag = @import("diag.zig").Diag;

pub const version: u64 = 1;

pub const File = struct {
    platform: []const u8,
    url: []const u8,
    sha256: []const u8,
    size: u64,
};

pub const LockPin = struct {
    name: []const u8,
    version: []const u8,
    files: []const File,
};

/// One npm tarball, keyed `name@version` (one entry however many places in
/// the lockfiles name it).
pub const Npm = struct {
    key: []const u8,
    name: []const u8,
    version: []const u8,
    url: []const u8,
    /// What package-lock.json says (npm's sha512); the tarball was checked
    /// against it by `update`.
    sri512: []const u8,
    /// What the farm's CAS and `pinned_file` need.
    sha256: []const u8,
    size: u64,
};

pub const Lock = struct {
    pins: []const LockPin = &.{},
    npm: []const Npm = &.{},

    pub fn findPin(self: Lock, name: []const u8) ?LockPin {
        for (self.pins) |p| if (std.mem.eql(u8, p.name, name)) return p;
        return null;
    }

    pub fn findNpm(self: Lock, key: []const u8) ?Npm {
        for (self.npm) |n| if (std.mem.eql(u8, n.key, key)) return n;
        return null;
    }
};

pub fn findFile(p: LockPin, platform: []const u8) ?File {
    for (p.files) |f| if (std.mem.eql(u8, f.platform, platform)) return f;
    return null;
}

pub const header =
    \\# GENERATED by kpin. Do not edit by hand; regenerate with:
    \\#   ./buck2 run komira//tools/build/kpin -- lock
    \\# `kpin check` fails when this file is stale, and when a hash changed for
    \\# a version that was already locked (tools/build/kpin/README.md).
    \\
;

fn lessFile(_: void, x: File, y: File) bool {
    return std.mem.lessThan(u8, x.platform, y.platform);
}
fn lessPin(_: void, x: LockPin, y: LockPin) bool {
    return std.mem.lessThan(u8, x.name, y.name);
}
fn lessNpm(_: void, x: Npm, y: Npm) bool {
    return std.mem.lessThan(u8, x.key, y.key);
}

pub const RenderError = error{ UnsafeValue, OutOfMemory };

fn checkFile(f: File) RenderError!void {
    // maxInt is what the reader stores for a size that is not an integer.
    if (f.size == std.math.maxInt(u64)) return error.UnsafeValue;
    if (!valid.isPinName(f.platform) or !valid.isUrl(f.url) or !valid.isSha256(f.sha256)) return error.UnsafeValue;
}

fn checkNpm(n: Npm, a: std.mem.Allocator) RenderError!void {
    if (n.size == std.math.maxInt(u64)) return error.UnsafeValue;
    const want = try std.fmt.allocPrint(a, "{s}@{s}", .{ n.name, n.version });
    defer a.free(want);
    if (!valid.isPackageName(n.name) or !valid.isVersion(n.version) or !std.mem.eql(u8, want, n.key)) return error.UnsafeValue;
    if (!valid.isUrl(n.url) or !valid.isSri512(n.sri512) or !valid.isSha256(n.sha256)) return error.UnsafeValue;
}

/// The lock as text. Sorts (copies of) the entries, so the order the caller
/// built them in never shows.
pub fn render(a: std.mem.Allocator, lock: Lock) RenderError![]u8 {
    var out = std.ArrayListUnmanaged(u8){};
    errdefer out.deinit(a);
    const w = out.writer(a);
    try w.writeAll(header);
    try w.print("\nKPIN_LOCK_VERSION = {d}\n\nPINS = {{", .{version});

    const pins = try a.dupe(LockPin, lock.pins);
    defer a.free(pins);
    std.mem.sort(LockPin, pins, {}, lessPin);
    if (pins.len == 0) try w.writeAll("}\n") else {
        try w.writeAll("\n");
        for (pins, 0..) |p, i| {
            if (!valid.isPinName(p.name) or !valid.isVersion(p.version)) return error.UnsafeValue;
            if (i > 0 and std.mem.eql(u8, pins[i - 1].name, p.name)) return error.UnsafeValue;
            try w.print("    \"{s}\": {{\n        \"version\": \"{s}\",\n        \"files\": {{\n", .{ p.name, p.version });
            const files = try a.dupe(File, p.files);
            defer a.free(files);
            std.mem.sort(File, files, {}, lessFile);
            for (files, 0..) |f, j| {
                try checkFile(f);
                if (j > 0 and std.mem.eql(u8, files[j - 1].platform, f.platform)) return error.UnsafeValue;
                try w.print(
                    "            \"{s}\": {{\n                \"url\": \"{s}\",\n                \"sha256\": \"{s}\",\n                \"size\": {d},\n            }},\n",
                    .{ f.platform, f.url, f.sha256, f.size },
                );
            }
            try w.writeAll("        },\n    },\n");
        }
        try w.writeAll("}\n");
    }

    try w.writeAll("\nNPM = {");
    const npm = try a.dupe(Npm, lock.npm);
    defer a.free(npm);
    std.mem.sort(Npm, npm, {}, lessNpm);
    if (npm.len == 0) try w.writeAll("}\n") else {
        try w.writeAll("\n");
        for (npm, 0..) |n, i| {
            try checkNpm(n, a);
            if (i > 0 and std.mem.eql(u8, npm[i - 1].key, n.key)) return error.UnsafeValue;
            try w.print(
                "    \"{s}\": {{\n        \"name\": \"{s}\",\n        \"version\": \"{s}\",\n        \"url\": \"{s}\",\n        \"sri512\": \"{s}\",\n        \"sha256\": \"{s}\",\n        \"size\": {d},\n    }},\n",
                .{ n.key, n.name, n.version, n.url, n.sri512, n.sha256, n.size },
            );
        }
        try w.writeAll("}\n");
    }
    return out.toOwnedSlice(a);
}

// ---- the reader ------------------------------------------------------------

const V = union(enum) {
    str: []const u8,
    int: u64,
    dict: []const KV,
};
const KV = struct { k: []const u8, v: V };

const Parser = struct {
    a: std.mem.Allocator,
    s: []const u8,
    i: usize = 0,
    err: ?[]const u8 = null,

    fn fail(self: *Parser, msg: []const u8) error{Syntax} {
        if (self.err == null) self.err = msg;
        return error.Syntax;
    }

    fn skip(self: *Parser) void {
        while (self.i < self.s.len) {
            const c = self.s[self.i];
            if (c == ' ' or c == '\t' or c == '\r' or c == '\n') {
                self.i += 1;
            } else if (c == '#') {
                while (self.i < self.s.len and self.s[self.i] != '\n') self.i += 1;
            } else break;
        }
    }

    fn eat(self: *Parser, c: u8) bool {
        self.skip();
        if (self.i < self.s.len and self.s[self.i] == c) {
            self.i += 1;
            return true;
        }
        return false;
    }

    fn string(self: *Parser) error{ Syntax, OutOfMemory }![]const u8 {
        self.skip();
        if (self.i >= self.s.len or self.s[self.i] != '"') return self.fail("expected a string");
        self.i += 1;
        const start = self.i;
        while (self.i < self.s.len and self.s[self.i] != '"') : (self.i += 1) {
            if (self.s[self.i] == '\\' or self.s[self.i] == '\n') return self.fail("a string has a backslash or a newline");
        }
        if (self.i >= self.s.len) return self.fail("a string is not closed");
        const r = self.s[start..self.i];
        self.i += 1;
        return r;
    }

    fn value(self: *Parser) error{ Syntax, OutOfMemory }!V {
        self.skip();
        if (self.i >= self.s.len) return self.fail("unexpected end of file");
        const c = self.s[self.i];
        if (c == '"') return .{ .str = try self.string() };
        if (c >= '0' and c <= '9') {
            const start = self.i;
            while (self.i < self.s.len and self.s[self.i] >= '0' and self.s[self.i] <= '9') self.i += 1;
            const n = std.fmt.parseInt(u64, self.s[start..self.i], 10) catch return self.fail("integer out of range");
            return .{ .int = n };
        }
        if (c == '{') {
            self.i += 1;
            var kvs = std.ArrayListUnmanaged(KV){};
            while (true) {
                if (self.eat('}')) break;
                const k = try self.string();
                if (!self.eat(':')) return self.fail("expected `:`");
                const v = try self.value();
                try kvs.append(self.a, .{ .k = k, .v = v });
                if (self.eat(',')) continue;
                if (self.eat('}')) break;
                return self.fail("expected `,` or `}`");
            }
            return .{ .dict = try kvs.toOwnedSlice(self.a) };
        }
        return self.fail("expected a string, an integer or a { dict }");
    }
};

fn get(d: []const KV, k: []const u8) ?V {
    for (d) |kv| if (std.mem.eql(u8, kv.k, k)) return kv.v;
    return null;
}

fn onlyKeys(d: []const KV, comptime keys: []const []const u8) bool {
    outer: for (d) |kv| {
        inline for (keys) |k| if (std.mem.eql(u8, kv.k, k)) continue :outer;
        return false;
    }
    return d.len == keys.len;
}

fn strOf(v: ?V) ?[]const u8 {
    const x = v orelse return null;
    return switch (x) {
        .str => |s| s,
        else => null,
    };
}

fn intOf(v: ?V) ?u64 {
    const x = v orelse return null;
    return switch (x) {
        .int => |n| n,
        else => null,
    };
}

fn dictOf(v: V) ?[]const KV {
    return switch (v) {
        .dict => |d| d,
        else => null,
    };
}

/// Reads a lock `render` wrote (or any text with the same literals). Every
/// value is validated as `render` would validate it. Problems go to `diag`.
pub fn parse(a: std.mem.Allocator, text: []const u8, diag: *Diag) error{Invalid}!Lock {
    var p = Parser{ .a = a, .s = text };
    var pins_v: ?[]const KV = null;
    var npm_v: ?[]const KV = null;
    var ver: ?u64 = null;
    while (true) {
        p.skip();
        if (p.i >= text.len) break;
        const start = p.i;
        while (p.i < text.len and (std.ascii.isAlphanumeric(text[p.i]) or text[p.i] == '_')) p.i += 1;
        const ident = text[start..p.i];
        if (ident.len == 0 or !p.eat('=')) {
            diag.add("lock: expected `NAME = value` at byte {d}", .{start});
            return error.Invalid;
        }
        const v = p.value() catch {
            diag.add("lock: {s} (near byte {d})", .{ p.err orelse "out of memory", p.i });
            return error.Invalid;
        };
        if (std.mem.eql(u8, ident, "KPIN_LOCK_VERSION")) {
            ver = intOf(v);
        } else if (std.mem.eql(u8, ident, "PINS")) {
            pins_v = dictOf(v);
        } else if (std.mem.eql(u8, ident, "NPM")) {
            npm_v = dictOf(v);
        } else {
            diag.add("lock: unknown top-level name {s}", .{ident});
            return error.Invalid;
        }
    }
    if (ver == null or ver.? != version) {
        diag.add("lock: KPIN_LOCK_VERSION must be {d}", .{version});
        return error.Invalid;
    }
    const before = diag.count();
    var pins = std.ArrayListUnmanaged(LockPin){};
    for (pins_v orelse &[_]KV{}) |kv| {
        const d = dictOf(kv.v) orelse {
            diag.add("lock: PINS[{s}] is not a dict", .{kv.k});
            continue;
        };
        if (!onlyKeys(d, &.{ "version", "files" })) {
            diag.add("lock: PINS[{s}] must have exactly version and files", .{kv.k});
            continue;
        }
        const pv = strOf(get(d, "version")) orelse "";
        const fd = dictOf(get(d, "files").?) orelse &[_]KV{};
        if (!valid.isPinName(kv.k) or !valid.isVersion(pv)) {
            diag.add("lock: PINS[{s}] has a bad name or version", .{kv.k});
            continue;
        }
        var files = std.ArrayListUnmanaged(File){};
        for (fd) |fkv| {
            const fdd = dictOf(fkv.v) orelse &[_]KV{};
            if (!onlyKeys(fdd, &.{ "url", "sha256", "size" })) {
                diag.add("lock: PINS[{s}][{s}] must have exactly url, sha256 and size", .{ kv.k, fkv.k });
                continue;
            }
            const f = File{
                .platform = fkv.k,
                .url = strOf(get(fdd, "url")) orelse "",
                .sha256 = strOf(get(fdd, "sha256")) orelse "",
                .size = intOf(get(fdd, "size")) orelse std.math.maxInt(u64),
            };
            checkFile(f) catch {
                diag.add("lock: PINS[{s}][{s}] has a malformed field", .{ kv.k, fkv.k });
                continue;
            };
            files.append(a, f) catch return error.Invalid;
        }
        pins.append(a, .{ .name = kv.k, .version = pv, .files = files.toOwnedSlice(a) catch return error.Invalid }) catch return error.Invalid;
    }
    var npm = std.ArrayListUnmanaged(Npm){};
    for (npm_v orelse &[_]KV{}) |kv| {
        const d = dictOf(kv.v) orelse &[_]KV{};
        if (!onlyKeys(d, &.{ "name", "version", "url", "sri512", "sha256", "size" })) {
            diag.add("lock: NPM[{s}] must have exactly name, version, url, sri512, sha256 and size", .{kv.k});
            continue;
        }
        const n = Npm{
            .key = kv.k,
            .name = strOf(get(d, "name")) orelse "",
            .version = strOf(get(d, "version")) orelse "",
            .url = strOf(get(d, "url")) orelse "",
            .sri512 = strOf(get(d, "sri512")) orelse "",
            .sha256 = strOf(get(d, "sha256")) orelse "",
            .size = intOf(get(d, "size")) orelse std.math.maxInt(u64),
        };
        checkNpm(n, a) catch {
            diag.add("lock: NPM[{s}] has a malformed field", .{kv.k});
            continue;
        };
        npm.append(a, n) catch return error.Invalid;
    }
    if (diag.count() != before) return error.Invalid;
    return .{
        .pins = pins.toOwnedSlice(a) catch return error.Invalid,
        .npm = npm.toOwnedSlice(a) catch return error.Invalid,
    };
}
